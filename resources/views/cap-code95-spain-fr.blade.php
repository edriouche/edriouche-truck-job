<div class="card">
<h2>📌 📌 Pourquoi ce sujet est-il important ?</h2>
<p>De nombreux conducteurs marocains entendent qu’ils peuvent obtenir le CAP / Code 95 en Pologne ou en Lituanie, puis travailler directement en Espagne. Cette question nécessite une explication claire, car plusieurs notions différentes sont souvent confondues : permis de conduire, qualification professionnelle, contrat de travail et autorisation de résidence et de travail.</p>
</div>

<div class="card">
<h2>🚛 1. Qu’est-ce que le CAP / Code 95 ?</h2>
<p>Le CAP / Code 95 est lié à la qualification professionnelle des conducteurs de véhicules de transport routier. Dans l’Union européenne, cette qualification est encadrée par des règles européennes et nationales.</p>

<p>Pour travailler comme conducteur professionnel de poids lourd, il ne suffit pas de posséder une catégorie C ou CE sur son permis de conduire. Il faut également vérifier les exigences de qualification professionnelle applicables au conducteur et au travail qu’il va effectuer.</p>
</div>

<div class="card">
<h2>📋 2. CAP / Code 95, travail et résidence</h2>
