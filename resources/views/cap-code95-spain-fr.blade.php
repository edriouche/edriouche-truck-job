<p>La possession du Code 95 ne transforme pas automatiquement un permis de conduire marocain en permis espagnol et ne donne pas, à elle seule, le droit de résider ou de travailler en Espagne.</p>
</div>

<div class="card">
<h2>🇵🇱🇱🇹 3. Un conducteur marocain peut-il obtenir le Code 95 en Pologne ou en Lituanie puis travailler en Espagne ?</h2>

<p>Cette question ne doit pas être résumée ainsi : « Je vais en Pologne ou en Lituanie comme touriste, j’obtiens le Code 95 et je peux ensuite travailler librement en Espagne ».</p>

<p>La situation réelle dépend de plusieurs éléments : la base juridique de la qualification, le permis de conduire utilisé, la résidence du conducteur, la validité des documents et surtout le droit légal de travailler et de résider en Espagne.</p>

<p>Ainsi, obtenir une qualification professionnelle dans un autre État membre de l’Union européenne ne signifie pas automatiquement que le conducteur dispose d’une autorisation de travail espagnole.</p>
</div>

<div class="card">
<h2>🇱🇹 4. Lituanie : que faut-il vérifier ?</h2>

<p>L’autorité lituanienne <strong>Regitra</strong> fournit des informations officielles sur les cartes de qualification de conducteur (DQC) et les exigences liées à la qualification professionnelle.</p>

<p>La DQC peut être liée à une qualification professionnelle reconnue dans le cadre européen, mais elle ne doit pas être confondue avec une autorisation de résidence ou de travail en Espagne.</p>

<p>Avant de payer une formation ou une procédure, le conducteur doit vérifier directement :</p>

<ul>
<li>quel permis de conduire est utilisé ;</li>
<li>sur quelle base juridique la qualification est obtenue ;</li>
<li>quel document est délivré ;</li>
<li>pendant combien de temps il est valable ;</li>
<li>si la situation concrète permet de travailler légalement en Espagne.</li>
</ul>
</div>

<div class="card">
<h2>🇵🇱 5. Pologne : que faut-il vérifier ?</h2>

<p>En Pologne également, il est nécessaire de vérifier la base juridique de la qualification professionnelle, le permis de conduire utilisé, la situation de résidence du conducteur et la validité des documents obtenus.</p>

<p>Il n’est pas correct de présenter comme une règle générale que « posséder un Code 95 polonais garantit le droit de travailler en Espagne ». Le droit de travailler en Espagne dépend également des règles espagnoles d’immigration et d’emploi applicables au ressortissant d’un pays hors Union européenne.</p>

<p>Par conséquent, avant tout paiement, il faut vérifier la procédure auprès des autorités compétentes et conserver les documents officiels attestant la qualification obtenue.</p>
</div>

<div class="card">
<h2>🇪🇸 6. Contrat de travail y autorización para trabajar en España</h2>

<p>Pour un conducteur marocain qui n’a pas déjà le droit de travailler en Espagne, l’obtention d’une qualification professionnelle ne remplace pas la procédure nécessaire pour obtenir une autorisation de résidence et de travail lorsqu’elle est exigée.</p>

<p>Un contrat ou une offre d’emploi d’une entreprise espagnole, ainsi que l’autorisation administrative correspondante, relèvent d’une procédure différente du Code 95.</p>

<p>Il faut donc clairement distinguer :</p>

<ul>
<li><strong>Qualification professionnelle :</strong> demuestra que se cumplen determinados requisitos profesionales.</li>
<li><strong>Contrat de travail:</strong> establece la relación laboral con una empresa.</li>
<li><strong>Autorisation de résidence et de travail :</strong> determina si el ciudadano extranjero puede residir y trabajar legalmente en España.</li>
</ul>
</div>

<div class="card">
<h2>⏳ 7. La question des 6 mois pour le permis étranger en Espagne</h2>

<p>La Direction générale de la circulation (DGT) établit des règles spécifiques pour conduire en Espagne avec certains permis de conduire étrangers.</p>

<p>Pour les permis provenant de pays ayant un accord d’échange, lorsque les conditions prévues sont remplies, la validité pour conduire peut être limitée à une période maximale de six mois à compter de l’acquisition de la résidence normale en Espagne.</p>

<p>Ainsi, un conducteur qui s’installe légalement en Espagne doit vérifier sa situation concrète et ne pas supposer qu’un permis étranger restera valable indéfiniment.</p>
</div>

<div class="card">
<h2>🇲🇦🇪🇸 8. Échange du permis de conduire marocain en Espagne</h2>

<p>Le Maroc fait partie des pays ayant un accord d’échange de permis de conduire avec l’Espagne.</p>

<p>Cependant, la procédure dépend de la catégorie du permis, des conditions de l’accord et de la situation concrète du conducteur. Pour certaines catégories professionnelles, comme C et D, des épreuves ou des exigences supplémentaires peuvent être prévues.</p>

<p>Le conducteur doit donc toujours consulter les informations actualisées de la DGT avant d’entamer la procédure.</p>
</div>

<div class="card">
<h2>🚛 9. Trois exemples pratiques</h2>

<h3>Exemple 1 — C+E sans Code 95</h3>
<p>Un conducteur peut posséder un permis C+E valide, mais cela ne signifie pas à lui seul qu’il remplit toutes les exigences de qualification professionnelle nécessaires pour travailler comme conducteur professionnel.</p>

<h3>Exemple 2 — C+E + Code 95 européen</h3>
<p>Le conducteur peut disposer d’une qualification professionnelle reconnue dans le cadre européen. Il doit néanmoins vérifier s’il remplit les conditions nécessaires pour travailler légalement en Espagne.</p>

<h3>Exemple 3 — C+E + Code 95 + entreprise espagnole</h3>
<p>Dans ce cas, plusieurs éléments de la procédure sont réunis, mais il faut encore vérifier la situation du permis de conduire, la qualification professionnelle et, le cas échéant, l’autorisation de résidence et de travail.</p>
</div>

<div class="card">
<h2>❌ 10. Ce que le Code 95 NE signifie PAS</h2>

<ul>
<li>Ce n’est pas un visa.</li>
<li>Ce n’est pas un titre de séjour en Espagne.</li>
<li>Ce n’est pas une autorisation de travail espagnole.</li>
<li>Il ne transforme pas automatiquement un permis de conduire marocain en permis espagnol.</li>
<li>Il ne garantit pas automatiquement un emploi.</li>
</ul>

<p>Le Code 95 est une qualification professionnelle. Les autres exigences doivent être analysées séparément selon la situation du conducteur.</p>
</div>

<div class="card">
<h2>🔎 11. Comment tout vérifier avant de payer ?</h2>

<p>Avant de payer une formation, une carte professionnelle ou toute autre procédure, le conducteur doit demander des informations claires et écrites.</p>

<ul>
<li>Quel document vais-je obtenir exactement ?</li>
<li>Quelle autorité officielle le délivre ?</li>
<li>Avec quel permis de conduire est-il obtenu ?</li>
<li>Quelle est la base juridique de la procédure ?</li>
<li>Où le document sera-t-il valable ?</li>
<li>La procédure me donne-t-elle le droit de travailler en Espagne ?</li>
<li>Qui se charge, le cas échéant, du contrat et de l’autorisation de résidence et de travail ?</li>
</ul>

<p>Si quelqu’un affirme qu’un Code 95 obtenu dans un autre pays garantit automatiquement un emploi en Espagne, il est important de demander la base juridique et de vérifier directement les informations auprès des autorités compétentes.</p>
</div>

<div class="card">
<h2>⚠️ 12. Attention aux promesses d’emploi</h2>

<p>Les conducteurs doivent se méfier de tout intermédiaire qui promet un emploi en Espagne uniquement en échange d’argent pour un prétendu Code 95.</p>

<p>Une qualification professionnelle et une autorisation de travail sont deux questions différentes. Avant de remettre de l’argent ou des documents personnels, il est recommandé de vérifier l’entreprise, le contrat, l’autorité qui délivre le document et la procédure légale applicable.</p>
</div>

<div class="card">
<h2>✅ Conclusion</h2>

<p>Pour un conducteur marocain, le Code 95 est un élément important de la qualification professionnelle, mais il ne doit pas être confondu avec le droit de résider ou de travailler en Espagne.</p>

<p>L’obtention d’une qualification en Pologne ou en Lituanie peut comporter des exigences spécifiques et doit être examinée selon la situation concrète du conducteur. Le permis de conduire, la qualification professionnelle, le contrat de travail et l’autorisation de résidence et de travail sont des éléments différents.</p>

<p><strong>Avant de payer ou de remettre des documents personnels, vérifiez toujours les informations auprès des autorités officielles.</strong></p>
</div>

