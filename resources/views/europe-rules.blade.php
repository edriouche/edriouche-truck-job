<h1>🇪🇺 قوانين القيادة والراحة والعمل والتاكوغراف في أوروبا</h1>

<p style="text-align:center;line-height:2;font-size:17px;">
دليل عملي للسائق المهني المغربي لفهم الفرق بين وقت القيادة،
وقت العمل، الاستراحة، والراحة اليومية والأسبوعية.
</p>

<div class="warning">
<strong>⚠️ ملاحظة مهمة:</strong><br>
قواعد القيادة والراحة لا تعني أن السائق يستطيع القيادة طوال مدة العمل.
هناك قواعد مستقلة للقيادة، وقواعد أخرى لوقت العمل، وقواعد للاستراحة والراحة.
ويجب دائمًا احترام القواعد الوطنية أو الجماعية الأكثر حماية عندما تكون مطبقة.
</div>

<div class="card">
<h2>🚛 1. الحد الأقصى للقيادة اليومية</h2>
<p>
القيادة اليومية العادية لا تتجاوز <strong>9 ساعات</strong>.
يمكن تمديدها إلى <strong>10 ساعات مرتين في الأسبوع</strong>.
</p>

<div class="example">
📌 <strong>مثال:</strong><br>
إذا قدت 4 ساعات ثم توقفت 45 دقيقة، يمكنك مواصلة القيادة.
لكن مجموع القيادة في ذلك اليوم يبقى خاضعًا للحد اليومي والأسبوعي.
</div>
</div>

<div class="card">
<h2>📅 2. الحد الأسبوعي وحد الأسبوعين</h2>
<p>
الحد الأقصى للقيادة هو <strong>56 ساعة في أسبوع واحد</strong>.
ولا يجوز أن يتجاوز مجموع القيادة <strong>90 ساعة خلال أسبوعين متتاليين</strong>.
</p>

<table class="table">
<tr>
<th>الفترة</th>
<th>الحد الأقصى للقيادة</th>
</tr>
<tr>
<td>يوم واحد</td>
<td>9 ساعات، ويمكن 10 ساعات مرتين في الأسبوع</td>
</tr>
<tr>
<td>أسبوع واحد</td>
<td>56 ساعة</td>
</tr>
<tr>
<td>أسبوعان متتاليان</td>
<td>90 ساعة</td>
</tr>
</table>
</div>

<div class="card">
<h2>☕ 3. استراحة بعد القيادة</h2>
<p>
بعد قيادة مدة أقصاها <strong>4 ساعات و30 دقيقة</strong> يجب أخذ
استراحة لا تقل عن <strong>45 دقيقة</strong>، ما لم تبدأ فترة راحة.
</p>

<p>
يمكن تقسيم استراحة 45 دقيقة إلى:
<strong>15 دقيقة ثم 30 دقيقة</strong>.
</p>

<div class="example">
📌 <strong>مثال صحيح:</strong><br>
قيادة 4:30 → استراحة 45 دقيقة → مواصلة القيادة.
<br><br>
📌 <strong>مثال بالتقسيم:</strong><br>
قيادة → استراحة 15 دقيقة → قيادة → استراحة 30 دقيقة.
</div>
</div>

<div class="card">
<h2>🛏️ 4. الراحة اليومية</h2>
<p>
خلال كل فترة 24 ساعة من بداية فترة الخدمة، يجب الحصول على راحة يومية مطلوبة.
الراحة اليومية العادية هي <strong>11 ساعة على الأقل</strong>.
</p>

<p>
يمكن تقسيم الراحة إلى:
<strong>3 ساعات + 9 ساعات = 12 ساعة</strong>.
</p>

<p>
كما يمكن استخدام راحة يومية مخفضة إلى <strong>9 ساعات</strong>،
بحد أقصى ثلاث مرات بين فترتي راحة أسبوعية.
</p>

<div class="example">
📌 <strong>مثال:</strong><br>
إذا انتهت فترة عملك وبدأت الراحة اليومية، يجب أن تخطط لوقت كافٍ
للحصول على فترة الراحة المطلوبة قبل بداية فترة العمل التالية.
</div>
</div>

<div class="card">
<h2>📆 5. الراحة الأسبوعية</h2>
<p>
الراحة الأسبوعية العادية هي <strong>45 ساعة متواصلة على الأقل</strong>.
ويمكن في الحالات المسموح بها تخفيضها إلى <strong>24 ساعة</strong> على الأقل،
مع تعويض النقص وفق القواعد.
</p>

<p>
بشكل عام يجب بدء الراحة الأسبوعية بعد ما لا يزيد عن
<strong>ست فترات متتالية من 24 ساعة</strong> منذ نهاية الراحة الأسبوعية السابقة.
</p>

<div class="example">
📌 <strong>مثال:</strong><br>
بعد نهاية الراحة الأسبوعية السابقة، لا يجوز للسائق الاستمرار بلا نهاية؛
يجب تنظيم الراحة الأسبوعية داخل الفترة القانونية.
</div>
</div>

<div class="card">
<h2>🏨 6. الراحة الأسبوعية 45 ساعة داخل الشاحنة</h2>
<p>
الراحة الأسبوعية العادية التي تبلغ 45 ساعة أو أكثر لا يجوز قضاؤها
داخل كابينة الشاحنة. يجب توفير مكان إقامة مناسب.
</p>

<p>
أما بعض فترات الراحة اليومية أو الراحة الأسبوعية المخفضة،
فيمكن قضاؤها في المركبة عندما تكون الشروط القانونية متوفرة
والشاحنة متوقفة.
</p>
</div>

<div class="card">
<h2>👷 7. ما الفرق بين وقت القيادة ووقت العمل؟</h2>
<p>
<strong>وقت القيادة ليس هو نفسه وقت العمل.</strong>
</p>

<p>
وقت العمل قد يشمل، حسب الحالة:
</p>

<ul style="line-height:2.2;">
<li>🚛 قيادة الشاحنة.</li>
<li>📦 تحميل وتفريغ البضائع.</li>
<li>🔧 بعض أعمال الصيانة والأعمال التقنية.</li>
<li>📋 مراقبة التحميل والتفريغ.</li>
<li>📝 بعض الإجراءات الإدارية المرتبطة بالنقل.</li>
</ul>

<div class="example">
📌 <strong>مثال عملي:</strong><br>
إذا بدأت العمل الساعة 08:00، وقُدت 4 ساعات،
ثم قضيت ساعتين في التحميل والتفريغ، ثم قدت ساعتين إضافيتين،
فإن يومك العملي ليس 6 ساعات فقط؛ لأن التحميل والتفريغ يدخلان في وقت العمل،
بينما حساب وقت القيادة يبقى منفصلًا.
</div>
</div>

<div class="card">
<h2>⏰ 8. الحد الأقصى لوقت العمل</h2>
<p>
متوسط وقت العمل لا يتجاوز <strong>48 ساعة في الأسبوع</strong>.
ويمكن أن يصل وقت العمل إلى <strong>60 ساعة في أسبوع</strong>
إذا بقي المتوسط عند 48 ساعة أو أقل خلال الفترة المرجعية المطلوبة،
والقاعدة العامة المذكورة أوروبيًا هي فترة 4 أشهر.
</p>

<p>
لذلك لا يجوز اعتبار قاعدة 60 ساعة أسبوعيًا
تصريحًا بالعمل 60 ساعة كل أسبوع بشكل مستمر.
</p>
</div>

<div class="card">
<h2>☕ 9. استراحات وقت العمل</h2>
<p>
هناك أيضًا قواعد خاصة باستراحة <strong>وقت العمل</strong>،
وهي ليست نفس قاعدة 45 دقيقة الخاصة بالقيادة.
</p>

<p>
وفق قواعد وقت العمل الأوروبية، لا ينبغي العمل أكثر من
<strong>6 ساعات متواصلة دون استراحة</strong>.
وتوجد قواعد إضافية لمدة الاستراحة حسب عدد ساعات العمل اليومية،
مع مراعاة القواعد الوطنية والاتفاقيات الجماعية المطبقة.
</p>

<div class="example">
📌 <strong>مهم للسائق:</strong><br>
استراحة 45 دقيقة المرتبطة بـ4 ساعات و30 دقيقة من القيادة
لا ينبغي الخلط بينها وبين جميع قواعد استراحة وقت العمل.
</div>
</div>

<div class="card">
<h2>🌙 10. العمل الليلي</h2>
<p>
عندما يؤدي السائق عملًا ليليًا، توجد قيود خاصة على وقت العمل.
القاعدة الأوروبية العامة تحدد ألا يتجاوز العمل
<strong>10 ساعات خلال أي فترة 24 ساعة</strong>
عندما تكون هناك فترة عمل ليلية، مع مراعاة القواعد الوطنية والتطبيقات القانونية.
</p>
</div>

<div class="card">
<h2>👥 11. القيادة بسائقين اثنين</h2>
<p>
في حالة وجود سائقين أو أكثر في المركبة وفق شروط
القيادة الجماعية (Multi-manning)، توجد قواعد خاصة
يمكن أن تسمح بتنظيم الراحة اليومية داخل فترة أطول من 24 ساعة.
</p>

<p>
لا ينبغي للسائق تطبيق هذه القاعدة على نفسه إلا عندما تتحقق
شروط القيادة بسائقين كما ينص عليها القانون.
</p>
</div>

<div class="card">
<h2>⛴️ 12. العبّارة أو القطار</h2>
<p>
هناك قواعد خاصة عندما تُنقل الشاحنة بواسطة عبّارة أو قطار،
وقد تسمح في حالات محددة بمقاطعة بعض فترات الراحة
بشروط معينة، منها توفر مكان نوم مناسب.
</p>

<p>
هذه حالة خاصة ولا تعني أن السائق يستطيع قطع الراحة متى شاء.
</p>
</div>

<div class="card">
<h2>⏱️ 13. التاكوغراف</h2>
<p>
التاكوغراف يسجل القيادة والاستراحات والراحة والعمل وفترات التوفر.
يجب على السائق استعماله بطريقة صحيحة وتسجيل النشاط المناسب.
</p>

<ul style="line-height:2.2;">
<li>🚛 القيادة.</li>
<li>🔨 العمل الآخر.</li>
<li>☕ الاستراحة.</li>
<li>🛏️ الراحة.</li>
<li>⏳ فترات التوفر عندما تنطبق.</li>
</ul>

<p>
عند استعمال التاكوغراف الرقمي، يجب استخدام بطاقة السائق الشخصية
قبل القيادة وعدم إعارتها إلى سائق آخر.
</p>
</div>

<div class="danger">
<h2>🚨 14. أخطاء خطيرة يجب تجنبها</h2>
<ul style="line-height:2.2;">
<li>❌ القيادة بعد تجاوز المدة القانونية.</li>
<li>❌ نسيان استراحة 45 دقيقة بعد 4 ساعات و30 دقيقة من القيادة.</li>
<li>❌ تسجيل نشاط غير صحيح على التاكوغراف.</li>
<li>❌ استعمال بطاقة سائق شخص آخر.</li>
<li>❌ اعتبار وقت التحميل والتفريغ وقت راحة تلقائيًا.</li>
<li>❌ اعتبار 60 ساعة عمل أسبوعيًا حقًا ثابتًا كل أسبوع.</li>
<li>❌ قضاء الراحة الأسبوعية العادية 45 ساعة داخل الكابينة.</li>
</ul>
</div>

<div class="warning">
<h2>🇲🇦 15. نصيحة خاصة للسائق المغربي</h2>
<p>
قبل العمل مع شركة أوروبية، تعلم هذه القواعد جيدًا،
واسأل الشركة عن طريقة تنظيم العمل والقيادة والراحة والتاكوغراف.
</p>

<p>
ولا تعتمد على قول شخص مثل:
<strong>«كل السائقين يفعلون ذلك»</strong>.
القانون هو المرجع، والشركة والسائق يتحملان مسؤولياتهما وفق القواعد المطبقة.
</p>

<p>
كما يجب التفريق بين:
<strong>رخصة السياقة + التأهيل المهني + بطاقة التاكوغراف + حق العمل والإقامة</strong>.
وجود وثيقة واحدة لا يعوض الوثائق أو الشروط الأخرى.
</p>
