<p style="font-size:36px;line-height:2.3;">
<strong>⚠️ Importante:</strong>
el conductor no debe pagar a intermediarios que prometan una tarjeta, una regularización o un empleo garantizado. Debe verificar siempre el procedimiento y dirigirse al organismo competente.
