<li>Conservar los certificados y justificantes de la formación realizada.</li>
<li>Verificar que el centro de formación esté autorizado.</li>
<li>Guardar copias de todos los documentos presentados para la renovación.</li>
<li>Si la formación o la renovación se realiza después de la fecha de caducidad, consultar a la administración competente sobre el procedimiento legal aplicable.</li>
</ul>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️ Importante:</strong>
el certificado de formación demuestra que se ha realizado la formación, pero no significa por sí solo que se hayan cumplido todas las condiciones necesarias para renovar la tarjeta.
