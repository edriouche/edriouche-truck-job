<h2 style="font-size:36px;line-height:1.8;text-align:center;">
1️⃣ Perte d'emploi et maintien de cotisations CNSS / AMO
</h2>

<p style="font-size:36px;line-height:2.3;">
L'un des problèmes qu'un conducteur professionnel peut rencontrer après la perte de son emploi est de constater, dans sa situation auprès de la Caisse Nationale de Sécurité Sociale (CNSS), des cotisations ou des montants réclamés pour une période pendant laquelle il ne travaillait plus effectivement.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚖️ Que dit le cadre juridique ?
</h3>

<p style="font-size:36px;line-height:2.3;">
Le décret n° 2.22.190 du 29 mars 2022 organise la situation des conducteurs titulaires d'une carte professionnelle, à l'exception des chauffeurs de taxi, en matière d'assurance maladie obligatoire de base et de régime de retraite applicables aux catégories des professionnels, travailleurs indépendants et personnes non salariées.
</p>

<p style="font-size:36px;line-height:2.3;">
Ce cadre juridique fixe les conditions d'affiliation, d'inscription et de cotisation pour la catégorie concernée.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚠️ La perte d'emploi ne suffit pas, à elle seule, pour déterminer le sort des cotisations
</h3>

<p style="font-size:36px;line-height:2.3;">
La perte d'un emploi ne signifie pas automatiquement que les cotisations cessent, pas plus qu'elle ne signifie automatiquement qu'elles continuent. Il faut d'abord déterminer le statut professionnel du conducteur, le régime dans lequel il est enregistré, la période concernée et la base juridique de l'inscription.
</p>

<p style="font-size:36px;line-height:2.3;">
Ainsi, si un conducteur perd son emploi et voit ensuite apparaître des cotisations ou des dettes dans sa situation auprès de la CNSS, il est nécessaire de vérifier la situation enregistrée au lieu de considérer automatiquement que le montant est correct ou incorrect.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 Que doit faire le conducteur ?
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Vérifier la situation enregistrée auprès de la CNSS.</li>
<li>Déterminer la date effective de fin de l'emploi.</li>
<li>Si le conducteur était salarié, vérifier que l'employeur a correctement déclaré la fin de la relation de travail.</li>
<li>Si le conducteur apparaît dans le régime des personnes non salariées, demander la raison et la date de début de cette inscription.</li>
<li>Comparer les cotisations réclamées avec la période pendant laquelle le conducteur travaillait effectivement.</li>
<li>Présenter les documents prouvant la situation professionnelle lors d'une demande de réexamen du compte.</li>
<li>Conserver le contrat de travail, l'attestation de travail, les documents de fin d'emploi et les notifications de la CNSS.</li>
<li>Demander une explication ou une révision de la situation lorsqu'il existe une différence entre la situation professionnelle réelle et l'inscription auprès de la caisse.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Règle pratique :</strong>
Perte d'emploi ≠ suppression automatique de l'inscription.
</p>


<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2️⃣ Relation entre le ministère du Transport et la CNSS
</h2>

<p style="font-size:36px;line-height:2.3;">
Il est important de distinguer clairement les compétences du ministère du Transport de celles de la Caisse Nationale de Sécurité Sociale (CNSS). Le ministère du Transport intervient dans l'organisation et la réglementation professionnelle liées à la conduite professionnelle et à la carte professionnelle du conducteur, tandis que la CNSS intervient dans l'inscription, la protection sociale et les cotisations selon le statut juridique et le régime social applicable.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🚛 Quel est le rôle du ministère du Transport ?
</h3>

<p style="font-size:36px;line-height:2.3;">
Le ministère du Transport intervient dans le cadre réglementaire et professionnel de la conduite professionnelle, notamment en ce qui concerne la carte professionnelle du conducteur et les conditions de qualification professionnelle.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🏛️ Quel est le rôle de la CNSS ?
</h3>

<p style="font-size:36px;line-height:2.3;">
La Caisse Nationale de Sécurité Sociale (CNSS) gère les régimes de protection sociale ainsi que l'inscription et les cotisations selon le statut juridique et le régime social auquel la personne est soumise.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚠️ La carte professionnelle ne signifie pas automatiquement que le conducteur est travailleur non salarié
</h3>

<p style="font-size:36px;line-height:2.3;">
La détention de la carte professionnelle ne signifie pas, à elle seule, que son titulaire est salarié ou travailleur non salarié et ne détermine pas, à elle seule, son régime de cotisation auprès de la CNSS. La situation sociale du conducteur doit être déterminée selon sa relation professionnelle réelle : travaille-t-il pour un employeur dans le cadre d'une relation de travail rémunérée, ou exerce-t-il une activité pour son propre compte selon les conditions légales applicables aux travailleurs non salariés ?
</p>

<h3 style="font-size:34px;line-height:1.8;">
🔎 Pourquoi cette distinction est-elle importante ?
</h3>

<p style="font-size:36px;line-height:2.3;">
Des difficultés peuvent apparaître lorsque la situation professionnelle réelle du conducteur ne correspond pas à la situation enregistrée auprès de la CNSS. Par exemple, un conducteur peut travailler pour une entreprise tout en apparaissant simultanément dans le régime des personnes non salariées, ou recevoir des demandes de cotisations après la fin de sa relation de travail. Dans ces situations, il faut examiner séparément l'inscription, la période concernée et la base juridique de chaque cotisation.
</p>

<h3 style="font-size:34px;line-height:1.8;">
📌 Conclusion
</h3>

<p style="font-size:36px;line-height:2.3;">
<strong>Ministère du Transport = aspect professionnel et réglementaire du conducteur.</strong><br>
<strong>CNSS = inscription, protection sociale et cotisations selon le régime juridique applicable.</strong>
</p>

<p style="font-size:32px;line-height:2.2;">
<strong>Attention :</strong> la carte professionnelle du conducteur ne suffit pas, à elle seule, à prouver qu'une personne est travailleur non salarié. De même, l'apparition de cotisations auprès de la CNSS ne suffit pas, à elle seule, à déterminer si le montant est correct ou incorrect. Il faut examiner la situation professionnelle et juridique réelle ainsi que les documents et les dates concernés.
</p>

