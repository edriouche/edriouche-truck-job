<p style="font-size:36px;line-height:2.3;">
أما السائقون الحاملون للبطاقة المهنية، غير سائقي سيارات الأجرة، فقد تم تحديد نظامهم الخاص لاحقاً بموجب المرسوم رقم 2.22.190 الصادر في 29 مارس 2022.
