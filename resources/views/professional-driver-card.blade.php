<h1 style="font-size:48px;line-height:1.8;text-align:center;">
🇲🇦 Carte professionnelle du conducteur au Maroc
</h1>

<h2 style="font-size:36px;line-height:1.8;text-align:center;font-weight:normal;">
Historique de la réglementation légale de la conduite professionnelle au Maroc
</h2>

<hr>

<p style="font-size:36px;line-height:2.3;">
La réglementation juridique moderne de la conduite professionnelle au Maroc a commencé avec la loi n° 52.05 relative au Code de la route, promulguée en 2010.
</p>

<p style="font-size:36px;line-height:2.3;">
Ensuite, le décret n° 2.10.314 du 29 septembre 2010 a été adopté pour réglementer la conduite professionnelle.
</p>

<p style="font-size:36px;line-height:2.3;">
Le législateur a prévu des dispositions transitoires pour les conducteurs qui exerçaient la conduite professionnelle avant le nouveau système, sous certaines conditions, pendant la période comprise entre :
</p>

<div style="font-size:36px;line-height:2.2;text-align:center;font-weight:bold;margin:25px 0;padding:18px;border:2px solid #ddd;">
📅 1er octobre 2008<br>
jusqu'au<br>
30 septembre 2010
</div>

<p style="font-size:36px;line-height:2.3;">
Ainsi, l'année 2009 est pertinente car elle se situe dans la période transitoire prévue par l'article 22 du décret n° 2.10.314. Cela ne signifie pas que 2009 soit l'année de création de la carte professionnelle.
</p>

<hr>


<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2013–2018 — Formation et application pratique
</h2>

<p style="font-size:36px;line-height:2.3;">
À partir de cette période, la formation continue est devenue un élément important du système de conduite professionnelle. En 2013, un programme national de formation continue obligatoire des conducteurs professionnels a été lancé.
</p>

<p style="font-size:36px;line-height:2.3;">
Le programme visait à former environ 140 000 conducteurs professionnels de transport de marchandises et de voyageurs durant la période 2014–2016, avec une généralisation progressive de la formation dans les différentes régions du Maroc.
</p>

<p style="font-size:36px;line-height:2.3;">
Cette étape a également posé des défis liés à la disponibilité des centres de formation, des ressources humaines et des moyens nécessaires pour accompagner le nombre important de conducteurs concernés.
</p>

<hr>

<p style="font-size:30px;line-height:2.2;">

<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2019–2021 — La transition vers la protection sociale
</h2>

<p style="font-size:36px;line-height:2.3;">
Durant cette période, le cadre juridique de la protection sociale destiné aux professionnels, aux travailleurs indépendants et aux personnes non salariées s'est développé à travers les lois n° 98.15 et 99.15.
</p>

<p style="font-size:36px;line-height:2.3;">
En 2021, le décret n° 2.21.929 a été adopté dans le cadre de l'application de ces deux régimes de protection sociale.
</p>

<p style="font-size:36px;line-height:2.3;">
Pour les conducteurs titulaires de la carte professionnelle autres que les chauffeurs de taxi, le régime spécifique a été établi ultérieurement par le décret n° 2.22.190 du 29 mars 2022.
</p>

<hr>

<h2>2022–2024 — Régime spécifique et débat sur la protection sociale</h2>
<p>En 2022, le décret n° 2.22.190 a établi un régime spécifique d'assurance maladie obligatoire et de retraite pour les conducteurs professionnels titulaires de la carte professionnelle, à l'exception des conducteurs de taxi.</p>
<p>Ce régime prévoyait l'affiliation à la protection sociale ainsi que la déclaration des cotisations correspondantes. Son application a ensuite soulevé des questions pratiques liées à l'inscription, aux cotisations et à l'accès à la couverture.</p>
<p>En 2023, ces difficultés ont également fait l'objet de débats parlementaires. Le projet de loi n° 41.23, provenant de la Chambre des représentants et examiné par la Chambre des conseillers, concernait notamment certaines dettes de cotisations, majorations, frais et amendes envers la CNSS.</p>
<p>Ce débat parlementaire est important dans l'histoire de la carte professionnelle : il montre que les difficultés de mise en œuvre de la protection sociale ont été discutées au niveau institutionnel et ne doivent pas être attribuées automatiquement à la carte professionnelle elle-même.</p>

<h2>2025–2026 — Problèmes actuels et débat parlementaire</h2>
<p>En 2025–2026, les difficultés liées à la protection sociale des conducteurs professionnels ont continué à faire l'objet de questions parlementaires.</p>
<p>À la Chambre des représentants, des questions ont été posées concernant d'éventuelles situations de double affiliation et de double cotisation lorsqu'un conducteur travaille pour une entreprise déclarée à la CNSS mais apparaît également comme travailleur non salarié.</p>
<p>Des questions ont également porté sur les conducteurs temporairement sans emploi ou en formation professionnelle qui peuvent recevoir des demandes de cotisations, ainsi que sur l'accumulation des dettes et les modalités de régularisation.</p>
<p>Ces questions parlementaires ne signifient pas que tous les conducteurs se trouvent dans la même situation. Elles montrent toutefois que l'application pratique du système de protection sociale pour cette catégorie continue de faire l'objet d'un suivi institutionnel.</p>
<p><strong>Important :</strong> la carte professionnelle, à elle seule, ne doit pas être confondue avec un contrat de travail, une affiliation salariale à la CNSS ou une qualité automatique de travailleur non salarié. La situation doit être examinée selon la relation de travail et le régime de protection sociale applicable.</p>

