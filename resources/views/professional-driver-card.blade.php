<p style="font-size:36px;line-height:2.3;">
كان البرنامج يستهدف تكوين حوالي 140 ألف سائق مهني في نقل البضائع ونقل المسافرين خلال الفترة 2014–2016، مع تعميم التكوين تدريجياً على مختلف جهات المملكة.
</p>

<p style="font-size:36px;line-height:2.3;">
كما طرحت هذه المرحلة تحديات مرتبطة بتوفير مراكز التكوين والموارد البشرية والوسائل اللازمة لمواكبة العدد الكبير من السائقين المعنيين.
