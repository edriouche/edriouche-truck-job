🇲🇦 Tarjeta profesional del conductor en Marruecos
</h1>

<h2 style="font-size:36px;line-height:1.8;text-align:center;font-weight:normal;">
Historia de la regulación legal de la conducción profesional en Marruecos
</h2>

<hr>

<p style="font-size:36px;line-height:2.3;">
La regulación legal moderna de la conducción profesional en Marruecos comenzó con la Ley nº 52.05, relativa al Código de la Circulación por Carretera, promulgada en 2010.
</p>

<p style="font-size:36px;line-height:2.3;">
Posteriormente se promulgó el Decreto nº 2.10.314, de 29 de septiembre de 2010, para regular la conducción profesional.
</p>

<p style="font-size:36px;line-height:2.3;">
El legislador estableció disposiciones transitorias para los conductores que ejercían profesionalmente antes del nuevo sistema, bajo determinadas condiciones, durante el período comprendido entre:
</p>

<div style="font-size:36px;line-height:2.2;text-align:center;font-weight:bold;margin:25px 0;padding:18px;border:2px solid #ddd;">
📅 1 de octubre de 2008<br>
hasta<br>
30 de septiembre de 2010
</div>

<p style="font-size:36px;line-height:2.3;">
Por ello, el año 2009 es relevante porque se encuentra dentro del período transitorio previsto por el artículo 22 del Decreto nº 2.10.314. Esto no significa que 2009 sea el año de creación de la tarjeta profesional.
</p>

<hr>


<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2013–2018 — Formación y aplicación práctica
</h2>

<p style="font-size:36px;line-height:2.3;">
A partir de esta etapa, la formación continua pasó a ocupar un lugar importante en el sistema de conducción profesional. En 2013 se puso en marcha un programa nacional de formación continua obligatoria para los conductores profesionales.
</p>

<p style="font-size:36px;line-height:2.3;">
El programa tenía como objetivo formar aproximadamente a 140.000 conductores profesionales de transporte de mercancías y de viajeros durante el período 2014–2016, con una ampliación progresiva de la formación a las diferentes regiones de Marruecos.
</p>

<p style="font-size:36px;line-height:2.3;">
Esta etapa planteó también retos relacionados con la disponibilidad de centros de formación, recursos humanos y medios suficientes para atender al elevado número de conductores afectados.
</p>

<hr>

<p style="font-size:30px;line-height:2.2;">

<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2019–2021 — La transición hacia la protección social
</h2>

<p style="font-size:36px;line-height:2.3;">
Durante este período se desarrolló el marco jurídico de protección social destinado a los profesionales, trabajadores independientes y personas no asalariadas, mediante las leyes nº 98.15 y 99.15.
</p>

<p style="font-size:36px;line-height:2.3;">
En 2021 se adoptó el Decreto nº 2.21.929, dentro de la aplicación de estos dos sistemas de protección social.
</p>

<p style="font-size:36px;line-height:2.3;">
Para los conductores titulares de la tarjeta profesional que no son taxistas, el régimen específico se estableció posteriormente mediante el Decreto nº 2.22.190 de 29 de marzo de 2022.
</p>

<hr>

<h2>2022–2024 — Régimen específico y debate sobre la protección social</h2>
<p>En 2022, el Decreto nº 2.22.190 estableció un régimen específico de seguro obligatorio de enfermedad y de pensiones para los conductores profesionales titulares de la tarjeta profesional, excepto los conductores de taxi.</p>
<p>El régimen preveía la afiliación a la protección social y la declaración de las cotizaciones correspondientes. Su aplicación planteó posteriormente cuestiones prácticas relacionadas con el registro, las cotizaciones y el acceso a la cobertura.</p>
<p>En 2023, estas dificultades también fueron objeto de debate parlamentario. El Proyecto de Ley nº 41.23, procedente de la Cámara de Representantes y examinado por la Cámara de Consejeros, trató la situación de determinadas deudas de cotizaciones, recargos, gastos y multas frente a la CNSS.</p>
<p>Este debate parlamentario es importante para la historia de la tarjeta profesional: muestra que las dificultades de aplicación de la protección social fueron discutidas institucionalmente y no deben atribuirse automáticamente a la tarjeta profesional en sí.</p>

<h2>2025–2026 — Problemas actuales y debate parlamentario</h2>
<p>En 2025–2026, las dificultades relacionadas con la protección social de los conductores profesionales continuaron siendo objeto de preguntas parlamentarias.</p>
<p>En la Cámara de Representantes se plantearon preguntas sobre posibles situaciones de doble afiliación y doble cotización cuando un conductor trabaja para una empresa registrada en la CNSS pero aparece también como trabajador no asalariado.</p>
<p>También se plantearon cuestiones sobre conductores temporalmente desempleados o en formación profesional que pueden recibir reclamaciones de cotizaciones, así como sobre la acumulación de deudas y las modalidades de regularización.</p>
<p>Estas cuestiones parlamentarias no significan que todos los conductores se encuentren en la misma situación. Muestran, sin embargo, que la aplicación práctica del sistema de protección social para esta categoría continúa siendo objeto de seguimiento institucional.</p>
<p><strong>Importante:</strong> la tarjeta profesional, por sí sola, no debe confundirse con un contrato de trabajo, una afiliación salarial a la CNSS o una situación automática de trabajador no asalariado. La situación debe analizarse según la relación laboral y el régimen de protección social aplicable.</p>

