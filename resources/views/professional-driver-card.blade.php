<p style="font-size:36px;line-height:2.3;">
À partir de cette période, la formation continue est devenue un élément important du système de conduite professionnelle. En 2013, un programme national de formation continue obligatoire des conducteurs professionnels a été lancé.
</p>

<p style="font-size:36px;line-height:2.3;">
Le programme visait à former environ 140 000 conducteurs professionnels de transport de marchandises et de voyageurs durant la période 2014–2016, avec une généralisation progressive de la formation dans les différentes régions du Maroc.
</p>

<p style="font-size:36px;line-height:2.3;">
Cette étape a également posé des défis liés à la disponibilité des centres de formation, des ressources humaines et des moyens nécessaires pour accompagner le nombre important de conducteurs concernés.
</p>

<hr>

<p style="font-size:32px;line-height:2.2;">

<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2019–2021 — La transition vers la protection sociale
</h2>

<p style="font-size:36px;line-height:2.3;">
Durant cette période, le cadre juridique de la protection sociale destiné aux professionnels, aux travailleurs indépendants et aux personnes non salariées s'est développé à travers les lois n° 98.15 et 99.15.
</p>

<p style="font-size:36px;line-height:2.3;">
En 2021, le décret n° 2.21.929 a été adopté dans le cadre de l'application de ces deux régimes de protection sociale.
</p>

<p style="font-size:36px;line-height:2.3;">
Pour les conducteurs titulaires de la carte professionnelle autres que les chauffeurs de taxi, le régime spécifique a été établi ultérieurement par le décret n° 2.22.190 du 29 mars 2022.
</p>

