<h3 style="font-size:34px;line-height:1.8;">
🎓 Formación continua y renovación de la tarjeta profesional
</h3>

<p style="font-size:36px;line-height:2.3;">
El titular de la tarjeta profesional debe realizar la formación continua cada cinco años para poder renovar la tarjeta. La formación debe realizarse durante el último año de validez de la tarjeta.
