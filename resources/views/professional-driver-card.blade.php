<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2️⃣ العلاقة بين وزارة النقل وCNSS
</h2>
<p style="font-size:36px;line-height:2.3;">
يجب التمييز بوضوح بين اختصاص وزارة النقل واختصاص الصندوق الوطني للضمان الاجتماعي (CNSS). وزارة النقل تتولى الجانب التنظيمي والمهني المرتبط بممارسة السياقة المهنية وبطاقة السائق المهني، بينما يتولى CNSS التسجيل والحماية الاجتماعية والاشتراكات وفق الصفة القانونية والنظام الاجتماعي المطبق.
</p>
<h3 style="font-size:34px;line-height:1.8;">
🚛 ما دور وزارة النقل؟
</h3>
<p style="font-size:36px;line-height:2.3;">
وزارة النقل تتولى الجانب التنظيمي والمهني المرتبط بممارسة السياقة المهنية، ومنه الإطار المتعلق ببطاقة السائق المهني وشروط التأهيل المهني.
</p>
<h3 style="font-size:34px;line-height:1.8;">
🏛️ ما دور CNSS؟
</h3>
<p style="font-size:36px;line-height:2.3;">
الصندوق الوطني للضمان الاجتماعي (CNSS) يتولى تدبير أنظمة الحماية الاجتماعية والتسجيل والاشتراكات وفق الصفة القانونية والنظام الاجتماعي الذي يخضع له الشخص.
</p>
<h3 style="font-size:34px;line-height:1.8;">
⚠️ البطاقة المهنية لا تعني تلقائيًا أن السائق عامل غير أجير
</h3>
<p style="font-size:36px;line-height:2.3;">
حيازة بطاقة السائق المهني لا تعني، بمفردها، أن حاملها أجير أو عامل غير أجير، ولا تحدد وحدها نظام اشتراكه لدى CNSS. يجب تحديد الوضعية الاجتماعية للسائق بناءً على علاقته المهنية الفعلية: هل يعمل لحساب مشغل بعلاقة شغل وأجر، أم يمارس نشاطًا لحسابه الخاص وفق الشروط القانونية الخاصة بالعمال غير الأجراء.
</p>
<h3 style="font-size:34px;line-height:1.8;">
🔎 لماذا هذا التفريق مهم؟
</h3>
<p style="font-size:36px;line-height:2.3;">
قد تظهر إشكالات عندما تكون الوضعية المهنية الفعلية للسائق مختلفة عن الوضعية المسجلة لدى CNSS، مثل أن يعمل السائق لدى شركة ثم يظهر في الوقت نفسه ضمن نظام غير الأجراء، أو أن تستمر مطالبات باشتراكات بعد انتهاء علاقة العمل. في هذه الحالات يجب فحص التسجيل والفترة والأساس القانوني لكل اشتراك على حدة.
</p>
<h3 style="font-size:34px;line-height:1.8;">
📌 الخلاصة
</h3>
<p style="font-size:36px;line-height:2.3;">
<strong>وزارة النقل = الجانب المهني والتنظيمي للسائق.</strong><br>
<strong>CNSS = التسجيل والحماية الاجتماعية والاشتراكات وفق النظام القانوني المطبق.</strong>
</p>
<p style="font-size:32px;line-height:2.2;">
<strong>تنبيه:</strong> بطاقة السائق المهني وحدها لا تكفي لإثبات أن الشخص عامل غير أجير، كما أن ظهور اشتراكات لدى CNSS لا يكفي وحده للحكم على صحة المبلغ أو عدم صحته. يجب الرجوع إلى الوضعية المهنية والقانونية الفعلية والوثائق والتواريخ المعنية.
