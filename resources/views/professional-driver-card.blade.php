<h2 style="font-size:36px;line-height:1.8;text-align:center;">
1️⃣ Pérdida del empleo y mantenimiento de cotizaciones CNSS / AMO
</h2>

<p style="font-size:36px;line-height:2.3;">
Uno de los problemas que puede encontrar un conductor profesional después de perder su empleo es comprobar, al consultar su situación ante la Caja Nacional de Seguridad Social (CNSS), que aparecen cotizaciones o cantidades pendientes correspondientes a un período durante el cual ya no trabajaba efectivamente.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚖️ ¿Qué establece el marco legal?
</h3>

<p style="font-size:36px;line-height:2.3;">
El Decreto nº 2.22.190, de 29 de marzo de 2022, regula la situación de los conductores titulares de una tarjeta profesional, excepto los conductores de taxi, en relación con el seguro obligatorio de enfermedad y el régimen de pensiones aplicables a los profesionales, trabajadores independientes y personas no asalariadas.
</p>

<p style="font-size:36px;line-height:2.3;">
Este marco jurídico establece las condiciones de afiliación al régimen y las cotizaciones correspondientes para la categoría afectada.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚠️ Perder el empleo no basta por sí solo para determinar las cotizaciones
</h3>

<p style="font-size:36px;line-height:2.3;">
La pérdida del empleo no significa automáticamente que las cotizaciones deban detenerse, ni significa automáticamente que deban continuar. Primero deben determinarse la condición profesional del conductor, el régimen en el que está registrado, el período reclamado y la base jurídica de la afiliación.
</p>

<p style="font-size:36px;line-height:2.3;">
Por ello, si un conductor pierde su empleo y posteriormente aparecen cotizaciones o deudas en su situación ante la CNSS, es necesario comprobar la situación registrada en lugar de considerar automáticamente que la cantidad es correcta o incorrecta.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 ¿Qué debe hacer el conductor?
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Comprobar la situación registrada ante la CNSS.</li>
<li>Determinar la fecha efectiva de finalización del empleo.</li>
<li>Si era asalariado, comprobar que el empleador haya declarado correctamente el fin de la relación laboral.</li>
<li>Si aparece inscrito en el régimen de trabajadores no asalariados, solicitar el motivo y la fecha de inicio de dicha inscripción.</li>
<li>Comparar las cotizaciones reclamadas con el período durante el cual trabajó efectivamente.</li>
<li>Presentar los documentos que acrediten su situación profesional cuando solicite una revisión de su cuenta.</li>
<li>Conservar el contrato de trabajo, el certificado de trabajo, los documentos relativos al fin del empleo y las notificaciones de la CNSS.</li>
<li>Solicitar una explicación o una revisión si existe una diferencia entre la situación profesional real y la registrada ante la CNSS.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Regla práctica:</strong>
perder el empleo ≠ eliminación automática de la afiliación.
</p>

<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
2️⃣ Relación entre el Ministerio de Transportes y la CNSS
</h2>

<p style="font-size:36px;line-height:2.3;">
El Ministerio encargado del transporte interviene principalmente en la regulación de la profesión de conductor, las condiciones de acceso a la profesión, la tarjeta profesional y la formación exigida al conductor profesional.
</p>

<p style="font-size:36px;line-height:2.3;">
La Caja Nacional de Seguridad Social (CNSS), por su parte, interviene en materia de afiliación, cotizaciones y protección social según el régimen aplicable a la persona.
</p>

<h3 style="font-size:34px;line-height:1.8;">
⚠️ La tarjeta profesional no determina por sí sola la situación ante la CNSS
</h3>

<p style="font-size:36px;line-height:2.3;">
El hecho de poseer una tarjeta profesional de conductor no significa automáticamente que la persona sea trabajador asalariado, ni significa automáticamente que deba estar registrada como trabajador no asalariado.
</p>

<p style="font-size:36px;line-height:2.3;">
Para determinar correctamente la situación deben examinarse la relación profesional real, la actividad ejercida, las fechas correspondientes, los documentos disponibles, el régimen de afiliación y la base jurídica aplicada.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 ¿Qué debe comprobar el conductor?
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Identificar ante qué organismo aparece registrada cada situación.</li>
<li>Comprobar si estaba registrado como trabajador asalariado o bajo otro régimen.</li>
<li>Verificar las fechas de inicio y finalización de cada período de afiliación.</li>
<li>Comparar la situación registrada con su situación profesional real.</li>
<li>Conservar los contratos, certificados de trabajo, documentos de la tarjeta profesional y demás justificantes.</li>
<li>Solicitar una explicación oficial cuando exista una diferencia entre la situación real y los datos registrados.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Regla práctica:</strong>
la tarjeta profesional identifica la condición profesional del conductor, pero no sustituye la determinación de su situación laboral o de seguridad social ante la CNSS.
</p>

<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
3️⃣ Cómo demostrar la experiencia profesional del conductor
</h2>

<p style="font-size:36px;line-height:2.3;">
La tarjeta profesional demuestra la condición profesional del conductor, pero por sí sola no constituye necesariamente un certificado completo de toda su experiencia laboral.
</p>

<p style="font-size:36px;line-height:2.3;">
Cuando sea necesario demostrar la experiencia profesional, es importante presentar documentos que permitan comprobar los períodos de trabajo y la actividad realmente ejercida.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 Documentos que pueden ayudar a demostrar la experiencia
</h3>

<ul style="font-size:36px;line-height:2.3;">
<li>Contratos de trabajo y certificados de empleo.</li>
<li>Documentos que indiquen las fechas y la naturaleza del trabajo realizado.</li>
<li>Recibos de salario u otros documentos relacionados con la remuneración.</li>
<li>Justificantes de afiliación y cotizaciones ante la CNSS, cuando sean pertinentes.</li>
<li>Antiguos permisos de conducir y documentos profesionales.</li>
<li>Certificados de formación relacionados con la profesión.</li>
<li>Otros documentos oficiales que permitan establecer cronológicamente la actividad profesional.</li>
</ul>

<h3 style="font-size:34px;line-height:1.8;">
📁 Solución práctica
</h3>

<p style="font-size:36px;line-height:2.3;">
El conductor puede preparar un expediente cronológico con los documentos disponibles, indicando para cada período el empleador, la actividad realizada, las fechas y los justificantes correspondientes.
</p>

<p style="font-size:36px;line-height:2.3;">
Si existe una diferencia entre la experiencia realmente realizada y la información registrada administrativamente, puede solicitar una explicación y presentar los documentos que permitan comprobar su situación.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️ Importante:</strong> la tarjeta profesional no debe confundirse automáticamente con un certificado detallado de experiencia laboral. Los documentos exigidos pueden variar según el procedimiento, la administración o el empleador.
</p>

<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
4️⃣ Deudas y acumulación de cotizaciones
</h2>

<p style="font-size:36px;line-height:2.3;">
Un conductor puede descubrir que aparecen cotizaciones, deudas o recargos correspondientes a períodos en los que ya no estaba trabajando o en los que su situación profesional había cambiado.
</p>

<p style="font-size:36px;line-height:2.3;">
La existencia de una deuda registrada no significa por sí sola que esta sea correcta o incorrecta. Es necesario comprobar los períodos afectados, el régimen de afiliación, la situación profesional real y la base jurídica utilizada para calcular las cantidades reclamadas.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 ¿Qué debe comprobar el conductor?
</h3>

<ul style="font-size:36px;line-height:2.3;">
<li>El período exacto al que corresponde la deuda.</li>
<li>El régimen bajo el cual fueron calculadas las cotizaciones.</li>
<li>Si durante ese período ejercía realmente una actividad profesional.</li>
<li>Si existen errores, duplicaciones o períodos que no corresponden a su situación.</li>
<li>El importe de las cotizaciones, recargos u otros conceptos reclamados.</li>
<li>Los documentos que puedan demostrar su situación real durante esos períodos.</li>
</ul>

<h3 style="font-size:34px;line-height:1.8;">
🛠️ Solución práctica
</h3>

<p style="font-size:36px;line-height:2.3;">
El conductor puede solicitar a la entidad competente un detalle de las cantidades reclamadas, con los períodos y conceptos correspondientes, y compararlo con sus contratos, certificados de trabajo, documentos de afiliación y demás justificantes.
</p>

<p style="font-size:36px;line-height:2.3;">
Si se detecta una diferencia entre los datos registrados y la situación real, puede solicitar una revisión o corrección presentando los documentos que justifiquen su solicitud.
</p>

<p style="font-size:36px;line-height:2.3;">
Si después de la verificación se determina que las cantidades son efectivamente debidas, el conductor puede informarse sobre los mecanismos legales de regularización o pago disponibles para su situación.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️ Importante:</strong> antes de pagar o aceptar una cantidad, es recomendable conocer exactamente el período, el régimen y la base de la deuda, y conservar una copia de cualquier solicitud o respuesta administrativa.
</p>

<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
5️⃣ Doble afiliación y doble cotización
</h2>

<p style="font-size:36px;line-height:2.3;">
En algunos casos, un conductor puede descubrir que figura bajo más de un régimen de afiliación o que aparecen cotizaciones correspondientes al mismo período bajo situaciones diferentes.
</p>

<p style="font-size:36px;line-height:2.3;">
Por ejemplo, puede existir una diferencia entre la situación como trabajador asalariado y otra situación de afiliación. Esto no significa automáticamente que exista un error, pero requiere comprobar cuidadosamente las fechas, la actividad realizada, el régimen aplicado y la base jurídica de cada registro.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 ¿Qué debe comprobar el conductor?
</h3>

<ul style="font-size:36px;line-height:2.3;">
<li>Los períodos exactos de cada afiliación.</li>
<li>El régimen correspondiente a cada período.</li>
<li>Si realmente ejercía una actividad que justificaba cada afiliación.</li>
<li>Si existen períodos coincidentes o cotizaciones duplicadas.</li>
<li>La base jurídica utilizada para cada registro.</li>
<li>Los documentos que permitan demostrar su situación profesional real.</li>
</ul>

<h3 style="font-size:34px;line-height:1.8;">
🛠️ Solución práctica
</h3>

<p style="font-size:36px;line-height:2.3;">
El conductor puede solicitar un estado detallado de sus afiliaciones y cotizaciones, comparar las fechas con su actividad profesional y reunir los documentos correspondientes a cada período.
</p>

<p style="font-size:36px;line-height:2.3;">
Si aparecen dos registros o dos obligaciones para el mismo período y considera que no corresponden a su situación, puede solicitar una explicación y, cuando proceda, una revisión o corrección ante la entidad competente.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️ Importante:</strong> la existencia de dos registros no demuestra por sí sola que haya una doble cotización indebida. Es necesario examinar la situación concreta, los períodos, el régimen aplicable y los documentos disponibles.
</p>

<hr>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
🛠️ Soluciones prácticas para el conductor profesional
</h2>

<p style="font-size:36px;line-height:2.3;">
El conductor debe identificar primero su situación concreta antes de realizar cualquier trámite. La solución puede variar según su régimen, los períodos afectados, los documentos disponibles y el organismo competente.
</p>

<h3 style="font-size:34px;line-height:1.8;">
1️⃣ Si pierde su empleo y continúan apareciendo cotizaciones
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Comprobar la fecha efectiva de finalización del trabajo.</li>
<li>Conservar el certificado de trabajo y cualquier documento que confirme el final de la relación laboral.</li>
<li>Comprobar ante la CNSS las fechas y el régimen de afiliación registrados.</li>
<li>Comparar las cotizaciones registradas con los períodos en los que realmente trabajó.</li>
<li>Si existe una diferencia, presentar los documentos disponibles y solicitar una explicación o revisión.</li>
<li>Conservar una copia de la solicitud y de cualquier respuesta recibida.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Principio práctico:</strong>
la pérdida del empleo no debe confundirse automáticamente con la desaparición de todos los registros administrativos. Lo importante es comprobar qué situación figura oficialmente, para qué período y sobre qué base.
</p>

<h3 style="font-size:34px;line-height:1.8;">
2️⃣ Si aparecen deudas, recargos o cantidades pendientes
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Solicitar el detalle de la deuda y de los períodos correspondientes.</li>
<li>Comprobar el régimen de afiliación utilizado para calcular las cotizaciones.</li>
<li>Comparar las cantidades reclamadas con la situación profesional real durante esos períodos.</li>
<li>Comprobar si existen errores, duplicaciones o períodos que no corresponden a la actividad realizada.</li>
<li>Presentar los documentos disponibles y solicitar una revisión o corrección cuando exista una diferencia justificada.</li>
<li>Si después de la verificación la deuda resulta efectivamente debida, informarse sobre las vías legales de regularización o pago disponibles.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Regla práctica:</strong>
antes de pagar o aceptar una deuda, el conductor debe conocer el período, el régimen y el concepto exacto de las cantidades reclamadas, y conservar las pruebas de cualquier trámite realizado.
</p>

<h3 style="font-size:34px;line-height:1.8;">
3️⃣ Si el conductor aparece como trabajador no asalariado cuando trabajaba como asalariado
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Identificar el régimen y las fechas que figuran oficialmente.</li>
<li>Reunir el contrato de trabajo, certificado de empleo, recibos de salario y demás documentos disponibles.</li>
<li>Comparar estos documentos con los registros de afiliación y cotización.</li>
<li>Solicitar una explicación cuando exista una diferencia entre la situación laboral real y la situación registrada.</li>
<li>Presentar una solicitud de revisión o corrección cuando los documentos justifiquen dicha solicitud.</li>
<li>Conservar una copia de todos los documentos y respuestas administrativas.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Importante:</strong>
la tarjeta profesional no determina por sí sola si el conductor es asalariado o trabajador no asalariado. Esta cuestión debe analizarse según la relación profesional real, los períodos correspondientes y los documentos disponibles.
