<h2 style="font-size:36px;line-height:1.8;text-align:center;">
3️⃣ إثبات الخبرة المهنية للسائق
</h2>
<p style="font-size:36px;line-height:2.3;">
الخبرة المهنية للسائق لا تُثبت بمجرد حيازة بطاقة السائق المهني. فالبطاقة المهنية مرتبطة بالتأهيل والممارسة المهنية، بينما إثبات سنوات العمل يعتمد على الوثائق التي تثبت علاقة الشغل أو النشاط المهني والفترة التي تمت فيها الممارسة.
</p>
<h3 style="font-size:34px;line-height:1.8;">
📄 ما هي الوثائق التي يمكن أن تساعد في إثبات الخبرة؟
</h3>
<p style="font-size:36px;line-height:2.3;">
بحسب وضعية السائق، يمكن أن تشمل الوثائق المفيدة عقود العمل، وشهادات العمل، وبطاقة الشغل، ووثائق الأجر، والتصريحات أو بيانات التسجيل لدى CNSS، إضافة إلى أي وثائق مهنية أخرى تثبت طبيعة العمل ومدته. وبالنسبة للأجير، تنص مدونة الشغل على بيانات تتعلق بالتسجيل لدى CNSS في بطاقة الشغل، وعلى إثبات رقم التسجيل في شهادة العمل عند انتهاء علاقة الشغل.
</p>
<h3 style="font-size:34px;line-height:1.8;">
⚠️ البطاقة المهنية ≠ شهادة الخبرة
</h3>
<p style="font-size:36px;line-height:2.3;">
حيازة البطاقة المهنية لا تعني وحدها أن السائق لديه عدد معين من سنوات الخبرة، ولا تعوض شهادة العمل أو الوثائق التي تثبت مدة العمل الفعلية. لذلك من المهم أن يحتفظ السائق بملف مهني منظم يثبت مراحل عمله وتكوينه وخبرته.
</p>
<h3 style="font-size:34px;line-height:1.8;">
🚛 لماذا إثبات الخبرة مهم؟
</h3>
<p style="font-size:36px;line-height:2.3;">
قد يحتاج السائق إلى إثبات خبرته عند البحث عن عمل، أو عند تقديم ملف مهني، أو عند طلب الاعتراف بمساره المهني. وفي هذه الحالات يجب التمييز بين ما تثبته البطاقة المهنية وما تثبته وثائق العمل الفعلية.
</p>
<h3 style="font-size:34px;line-height:1.8;">
📌 قاعدة عملية للسائق
</h3>
<p style="font-size:36px;line-height:2.3;">
احتفظ بنسخ من عقود العمل، وشهادات العمل، وبطاقات الشغل، ووثائق الأجر، ووثائق CNSS، ووثائق التكوين والتأهيل، وأي وثيقة تثبت الفترة التي اشتغلت فيها وطبيعة العمل الذي قمت به.
</p>
<p style="font-size:32px;line-height:2.2;">
<strong>الخلاصة:</strong> البطاقة المهنية تثبت وضعًا مهنيًا وفق الإطار المنظم لها، لكنها لا تثبت وحدها عدد سنوات الخبرة. إثبات الخبرة يحتاج إلى وثائق مرتبطة بالعمل أو النشاط المهني والفترات المعنية.
</p>
<h2 style="font-size:36px;line-height:1.8;text-align:center;">
4️⃣ المديونية وتراكم الاشتراكات</h2>
<p style="font-size:36px;line-height:2.3;">قد يجد السائق المهني بعد توقف العمل أو تغير وضعيته الاجتماعية مبالغ أو اشتراكات ظاهرة في وضعيته لدى CNSS، وقد تتراكم هذه المبالغ مع مرور الوقت.</p>
<p style="font-size:36px;line-height:2.3;">ظهور مديونية أو اشتراكات متراكمة لا يعني وحده أن المبلغ صحيح أو غير صحيح. يجب التحقق من الفترة المعنية، والوضعية المسجلة لدى CNSS، وطبيعة النشاط أو العمل خلال تلك الفترة، والأساس القانوني للاشتراك.</p>
<p style="font-size:36px;line-height:2.3;">إذا كان السائق قد توقف عن العمل، فمن المهم الاحتفاظ بما يثبت تاريخ انتهاء العمل أو تغير الوضعية، مثل شهادة العمل أو وثيقة انتهاء العلاقة المهنية أو الوثائق المتعلقة بالتسجيل والتصريحات لدى CNSS، ثم طلب توضيح رسمي عن الفترات والمبالغ المحتسبة.</p>
<p style="font-size:36px;line-height:2.3;">ولا ينبغي الخلط بين البطاقة المهنية للسائق وبين الالتزام بأداء الاشتراكات: البطاقة المهنية لا تثبت وحدها وجود علاقة شغل أو نشاط مستقل خلال كل فترة، كما أن وجود مبلغ مستحق في الحساب لا يحسم وحده مدى صحة المديونية.</p>
<p style="font-size:36px;line-height:2.3;">عمليًا، يجب مقارنة كشف الاشتراكات مع فترات العمل الفعلية والوثائق المتوفرة، وطلب تصحيح أو مراجعة الوضعية عند وجود اختلاف أو تسجيل غير مطابق للواقع.</p>
