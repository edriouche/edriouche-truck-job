<h2 style="font-size:40px;line-height:1.8;text-align:center;">
الحلول العملية للسائق عند وجود مشكلة في وضعيته المهنية
</h2>

<h3 style="font-size:34px;line-height:1.8;">
🔎 فقدان العمل لا يعني تلقائيًا سقوط جميع الاشتراكات
</h3>

<p style="font-size:36px;line-height:2.3;">
إذا فقد السائق عمله لدى شركة، ثم ظهرت في حسابه اشتراكات مرتبطة بنظام السائقين غير الأجراء، فلا ينبغي اعتبار هذه المبالغ صحيحة أو خاطئة تلقائيًا. يجب أولًا معرفة الصفة التي سجل بها السائق، وتاريخ بداية التسجيل، والفترة التي احتُسبت عنها الاشتراكات، والأساس القانوني لذلك التسجيل.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>الحل العملي:</strong> يطلب السائق من الصندوق كشفًا مفصلًا عن وضعيته، ويقدم الوثائق التي تثبت انتهاء علاقة الشغل أو توقف النشاط، ثم يطلب مراجعة وتصحيح التسجيل والاشتراكات عن الفترات التي يثبت أنها لا تطابق وضعيته المهنية.
</p>

<h3 style="font-size:34px;line-height:1.8;">
💰 المديونية وغرامات التأخير
</h3>

<p style="font-size:36px;line-height:2.3;">
إذا ظهرت على حساب السائق مبالغ مستحقة أو غرامات تأخير، فمن المهم أولًا التحقق من أصل هذه المبالغ والفترة التي تخصها والصفة المهنية التي بني عليها التسجيل.
</p>

<p style="font-size:36px;line-height:2.3;">
لا تعني المديونية في حد ذاتها أن جميع المبالغ خاطئة، كما أن ظهورها في الحساب لا يمنع السائق من طلب مراجعة وضعية التسجيل إذا كان يعتقد أن هناك خطأ في الصفة أو الفترة أو البيانات المعتمدة.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>الحل العملي:</strong> يطلب السائق كشفًا تفصيليًا من الصندوق، ويقارن الفترات مع وثائق العمل والتصريحات، ثم يقدم طلب مراجعة أو تصحيح مدعومًا بالوثائق عند وجود اختلاف. وإذا تبين بعد المراجعة أن الاشتراكات مستحقة، يمكن الانتقال إلى إجراءات التسوية وفق القواعد المعمول بها.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🔎 إذا كان السائق أجيرًا وظهر له تسجيل ضمن نظام غير الأجراء
</h3>

<p style="font-size:36px;line-height:2.3;">
يجب أولًا تحديد الصفة التي سجل بها السائق والفترة التي تغطيها الاشتراكات. إذا كان يعمل بأجر لدى شركة، فعليه الاحتفاظ بعقد العمل وشهادات العمل ووثائق التصريح، وتقديمها عند طلب مراجعة التسجيل.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>الحل:</strong> لا يطلب السائق إلغاء المبالغ بشكل عام، بل يطلب تحديد سبب التسجيل والفترة المعنية، ثم مراجعة وتصحيح البيانات والاشتراكات إذا ثبت عدم توافقها مع وضعيته المهنية.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️</strong> البطاقة المهنية وحدها لا تكفي لإثبات طبيعة علاقة الشغل في كل حالة؛ يجب النظر أيضًا إلى الصفة المهنية والواقع والوثائق المتعلقة بالفترة المعنية.
</p>

<h3 style="font-size:34px;line-height:1.8;">
🧾 كيف يثبت السائق خبرته المهنية؟
</h3>

<p style="font-size:36px;line-height:2.3;">
الخبرة المهنية يجب أن تكون قابلة للإثبات بالوثائق، وليس بمجرد التصريح بعدد سنوات العمل.
</p>

<p style="font-size:36px;line-height:2.3;">
لذلك يُنصح السائق بالاحتفاظ بعقود العمل، وشهادات العمل، ووثائق التصريح، ووثائق الأجر عند توفرها، ورخص السياقة السابقة، وبطاقة السائق المهني وشهادات التكوين، وكل وثيقة رسمية يمكن أن تثبت مدة العمل وطبيعته.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>الحل العملي:</strong> عند طلب الاعتراف بالخبرة أو مراجعة الوضعية المهنية، يقدم السائق ملفًا مرتبًا زمنيًا يوضح الشركات التي عمل معها، والفترات، وطبيعة المهام، والوثائق التي تثبت كل فترة.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️</strong> إثبات الخبرة المهنية لا يعني تلقائيًا الإعفاء من شرط قانوني أو الحصول على مؤهل مهني؛ القرار النهائي يعود إلى الجهة المختصة وفق النصوص والإجراء المعمول به.
</p>

<h3 style="font-size:34px;line-height:1.8;">
📄 ماذا يفعل السائق إذا رُفض طلب البطاقة المهنية أو لم تُقبل وثائقه؟
</h3>

<p style="font-size:36px;line-height:2.3;">
يجب أولًا معرفة سبب عدم قبول الطلب والوثيقة أو الشرط الذي لم يتم استيفاؤه. ويُنصح السائق بالاحتفاظ بإثبات إيداع الطلب، ونسخ جميع الوثائق، وأي إشعار أو جواب يتعلق بالطلب.
</p>

<p style="font-size:36px;line-height:2.3;">
إذا كان السبب متعلقًا بوثيقة ناقصة أو غير مطابقة، يتم تصحيح الملف وإعادة تقديمه وفق المسطرة المعمول بها.
</p>

<p style="font-size:36px;line-height:2.3;">
أما إذا كان السائق يرى أن الرفض ناتج عن خطأ في تقييم وثيقته أو وضعيته، فيمكنه تقديم طلب مراجعة أو تظلم إلى الجهة المختصة، مع إرفاق الوثائق التي تدعم طلبه.
</p>

<p style="font-size:36px;line-height:2.3;">
<strong>⚠️</strong> لا ينبغي دفع مبالغ لأي وسيط مقابل وعد بضمان الحصول على البطاقة أو تجاوز الشروط القانونية. يجب الاعتماد على المسطرة والجهة المختصة والوثائق الرسمية.
</p>

<h2 style="font-size:36px;line-height:1.8;text-align:center;font-weight:normal;">
🎓 التكوين المستمر وتجديد بطاقة السائق المهني
</h2>

<p style="font-size:36px;line-height:2.2;">
يجب على حامل بطاقة السائق المهني متابعة التكوين المستمر كل خمس سنوات من أجل تجديد البطاقة، ويكون التكوين خلال السنة الأخيرة من مدة صلاحية البطاقة.
</p>

<p style="font-size:36px;line-height:2.2;">
وينص التنظيم على إيداع طلب التكوين لدى مؤسسة معتمدة في أجل أقصاه ثلاثة أشهر قبل انتهاء مدة صلاحية البطاقة.
</p>

<p style="font-size:36px;line-height:2.2;">
<strong>الحل العملي للسائق:</strong>
</p>

<ul style="font-size:36px;line-height:2.2;">
<li>التأكد من تاريخ انتهاء البطاقة وعدم الانتظار إلى آخر لحظة.</li>
<li>الاحتفاظ بشهادة كل تكوين مستمر.</li>
<li>التأكد من أن التكوين يتم لدى جهة معتمدة.</li>
<li>الاحتفاظ بنسخة من البطاقة وشهادة التكوين وباقي الوثائق.</li>
<li>إذا كان موعد التكوين بعد تاريخ انتهاء البطاقة، الاستفسار عن المسطرة القانونية المتعلقة بتمديد الصلاحية.</li>
</ul>

<p style="font-size:36px;line-height:2.2;">
⚠️ شهادة التكوين تثبت متابعة التكوين، لكنها لا تعني وحدها أن جميع شروط التجديد مستوفاة؛ فالملف يخضع للتحقق وفق المسطرة المعمول بها.
</p>

