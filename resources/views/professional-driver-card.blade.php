<h3 style="font-size:34px;line-height:1.8;">
4️⃣ Si el conductor necesita demostrar su experiencia profesional
</h3>

<ol style="font-size:36px;line-height:2.3;">
<li>Preparar un expediente cronológico de la experiencia profesional.</li>
<li>Reunir contratos, certificados de empleo y documentos que indiquen las fechas de trabajo.</li>
<li>Añadir, cuando sean pertinentes, recibos de salario y justificantes de afiliación o cotización.</li>
<li>Conservar antiguos permisos de conducir, documentos profesionales y certificados de formación.</li>
<li>Ordenar los documentos por períodos para facilitar la comprobación de la experiencia.</li>
<li>Si un organismo rechaza un documento o considera insuficiente la prueba, solicitar que indique el requisito o documento que falta.</li>
</ol>

<p style="font-size:36px;line-height:2.3;">
<strong>📌 Regla práctica:</strong>
cuanto más clara y cronológica sea la documentación presentada, más fácil será comprobar los períodos y la naturaleza de la experiencia profesional. Los documentos exigidos pueden variar según el procedimiento.
</p>

<h3 style="font-size:34px;line-height:1.8;">
5️⃣ Si se rechaza una solicitud o no se aceptan determinados documentos
