<h2 style="text-align:center;">🚛 Guía del conductor marroquí: de principiante a profesional</h2>

<p style="text-align:center;line-height:1.9;font-size:17px;">Esta guía ayuda al conductor a preparar su perfil para buscar trabajo y presentar su candidatura a las empresas de forma profesional y organizada.</p>

<h3>🟢 1. ¿Cómo empezar como conductor de camión?</h3>
<p style="line-height:2;">Empieza asegurándote de tener la categoría adecuada del permiso de conducir y adquiere formación y experiencia progresivamente. No busques solamente el primer empleo; busca un lugar que te ayude a construir una experiencia profesional real.</p>

<h3>📄 2. Prepara tu expediente profesional</h3>
<p style="line-height:2;">Prepara un expediente ordenado que incluya el CV, una foto profesional, el permiso de conducir, la tarjeta profesional de conductor, certificados de formación y experiencia, y cualquier certificado adicional requerido para el tipo de transporte en el que quieres trabajar.</p>

<h3>📝 3. ¿Cómo escribir un CV profesional?</h3>
<p style="line-height:2;">Incluye nombre, datos de contacto y ciudad, categorías del permiso, años de experiencia, tipos de camiones conducidos, tipos de transporte realizados, certificados y formación, y los idiomas. Mantén la información clara, honesta y concisa.</p>

<h3>📸 4. La foto profesional</h3>
<p style="line-height:2;">Utiliza una foto reciente, clara y adecuada para el trabajo, con un fondo sencillo y ropa apropiada. Evita fotos familiares o poco claras en el CV.</p>

<h3>📑 5. Organiza tus documentos</h3>
<p style="line-height:2;">Conserva copias claras y organizadas de tus documentos. Cuando la empresa solicite un archivo PDF, reúne solamente los documentos requeridos y ordénalos claramente.</p>

<h3>🔎 6. ¿Cómo buscar una empresa adecuada?</h3>
<p style="line-height:2;">Empieza por la página web oficial de la empresa y su página oficial de empleo. Comprueba el nombre de la empresa, su actividad y sus datos de contacto antes de enviar tu candidatura. No dependas de anuncios de origen desconocido.</p>

<h3>📧 7. ¿Cómo enviar una solicitud de empleo?</h3>
<p style="line-height:2;">Escribe un mensaje breve y respetuoso, indica el puesto que deseas y adjunta tu CV y los documentos solicitados. Utiliza el correo electrónico oficial o la plataforma oficial de empleo de la empresa cuando esté disponible.</p>

<h3>🤝 8. ¿Cómo prepararte para una entrevista?</h3>
<p style="line-height:2;">Revisa la información de la empresa, conoce el tipo de camión, el trabajo y la ruta prevista. Prepara tus documentos y responde con sinceridad sobre tu experiencia y tu capacidad para asumir la responsabilidad del camión y la carga.</p>

<h3>🚚 9. Consejos para el conductor en su primer trabajo</h3>
<p style="line-height:2;">Inspecciona el camión antes de salir, presta atención a la seguridad y a la sujeción de la carga, respeta las instrucciones de la empresa y las normas de circulación, y registra y comunica las averías o incidencias.</p>

<h3>⚠️ 10. Errores que debes evitar</h3>
<p style="line-height:2;">No pongas experiencia falsa en el CV, no envíes tus documentos a desconocidos y no aceptes condiciones que no entiendas. No pagues dinero a nadie a cambio de una promesa de empleo.</p>

<h3>🛡️ 11. Protégete de los intermediarios fraudulentos</h3>
<p style="line-height:2;">Trata directamente con la empresa siempre que sea posible. Verifica el correo electrónico, la página oficial y el nombre de la empresa antes de cualquier paso, y no consideres auténtico un contrato o una oferta hasta comprobar su fuente.</p>

