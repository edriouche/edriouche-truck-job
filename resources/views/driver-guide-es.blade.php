<h3 style="text-align:center;">📋 Modelo breve de información para el CV del conductor</h3>
<p style="line-height:2;">Nombre completo — teléfono — ciudad — categorías del permiso — años de experiencia — tipos de camiones — tipo de transporte — certificados y formación — idiomas — información adicional útil para el trabajo.</p>
