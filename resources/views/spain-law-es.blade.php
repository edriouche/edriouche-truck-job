<div class="card">
<h2>🎓 4. CAP — Cualificación del conductor profesional en España</h2>

<p>
El certificado <strong>CAP — Certificado de Aptitud Profesional</strong> está relacionado con la cualificación inicial y la formación continua de los conductores profesionales de transporte por carretera, de acuerdo con las normas españolas y europeas aplicables.
</p>

<div class="article">
<strong>Real Decreto 284/2021:</strong>
Regula en España la cualificación inicial y la formación continua de los conductores profesionales sujetos a estas normas.
</div>

<div class="article">
<strong>📅 Actualización importante en 2026:</strong>
Se publicó el <strong>Real Decreto 487/2026</strong> para modificar el Real Decreto 284/2021.
Algunas modificaciones publicadas en junio de 2026 entran en vigor el <strong>18 de septiembre de 2026</strong>. Por ello, es importante distinguir entre las normas actualmente vigentes y las modificaciones que todavía no han entrado en vigor.
</div>

<div class="info">
<strong>📌 Para el conductor que viene a trabajar a España:</strong>
Los requisitos del CAP dependen de la situación del conductor, del tipo de transporte, de su permiso de conducción, de su cualificación y de las normas que le sean aplicables. No debes suponer que tener un permiso de conducción extranjero significa automáticamente cumplir los requisitos del CAP.
</div>

</div>

<div class="card">
<h2>🚛 5. Antes de iniciar el viaje</h2>

<ul>
<li>✅ Comprueba el permiso de conducción y los documentos necesarios.</li>
<li>✅ Comprueba los requisitos del CAP si son aplicables a tu caso.</li>
<li>✅ Comprueba el tacógrafo y la forma correcta de registrar tu actividad.</li>
<li>✅ Revisa los tiempos de conducción, pausas y descansos.</li>
<li>✅ Comprueba el estado y la seguridad del vehículo.</li>
<li>✅ Asegúrate de que la carga está correctamente asegurada.</li>
<li>✅ Comprueba los documentos de la mercancía y del transporte.</li>
<li>✅ En el transporte de mercancías peligrosas, comprueba los requisitos ADR.</li>
<li>✅ Lleva contigo los documentos y registros exigidos durante el viaje.</li>
</ul>

</div>

<div class="card">
<h2>🔴 Errores que debes evitar</h2>

<ul>
<li>❌ Superar el límite legal de conducción.</li>
<li>❌ No respetar la pausa de 45 minutos después de 4 horas y media de conducción, según las normas.</li>
<li>❌ Reducir los períodos de descanso sin una base legal.</li>
<li>❌ Registrar incorrectamente la actividad en el tacógrafo.</li>
<li>❌ Utilizar una tarjeta de conductor que no esté a nombre del propio conductor.</li>
<li>❌ Utilizar medios para manipular el tacógrafo.</li>
<li>❌ Descuidar los documentos exigidos.</li>
<li>❌ Ignorar las normas de carga y seguridad.</li>
</ul>

