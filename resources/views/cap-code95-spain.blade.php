</header>

<div class="container">

<div class="card warning">
<h2>لماذا كتبنا هذا الموضوع؟</h2>
<p>تنتشر بين السائقين المغاربة معلومات مختلفة حول الحصول على CAP / Code 95 في بولندا أو ليتوانيا ثم الذهاب للعمل في إسبانيا. وفي كثير من الحالات يحدث خلط بين <strong>رخصة القيادة، والتأهيل المهني، وعقد العمل، وتصريح العمل والإقامة</strong>.</p>
<p>الهدف من هذه الصفحة هو شرح الفرق بين هذه الأمور بطريقة عملية، حتى لا يدفع السائق أموالًا بناءً على وعد غير واضح أو معلومة ناقصة.</p>
</div>

<div class="card">
<h2>1. ما هو CAP / Code 95؟</h2>
<p>Code 95 هو رمز أوروبي مرتبط بالتأهيل المهني للسائقين الذين يخضعون لقواعد التأهيل المهني لنقل البضائع أو الركاب.</p>
<p>حسب الدولة والإجراء، يمكن أن يظهر الرمز 95 في رخصة القيادة أو أن يثبت في <strong>بطاقة تأهيل السائق DQC</strong>.</p>
<p class="important">إذن Code 95 يتعلق بالتأهيل المهني، وليس هو نفسه رخصة القيادة، وليس تصريح إقامة أو تصريح عمل.</p>
</div>

<div class="card info">
<h2>2. الفرق بين رخصة القيادة وCode 95 والعمل والإقامة</h2>
<table>
<tr><th>الوثيقة أو الوضع</th><th>ماذا تعني؟</th><th>هل تكفي وحدها للعمل في إسبانيا؟</th></tr>
<tr><td><strong>رخصة C أو CE</strong></td><td>تثبت الفئة التي يحق للسائق قيادتها.</td><td>لا.</td></tr>
<tr><td><strong>Code 95 / DQC</strong></td><td>يثبت التأهيل المهني المطلوب عندما تنطبق قواعد التأهيل.</td><td>لا.</td></tr>
<tr><td><strong>عقد عمل</strong></td><td>يثبت وجود علاقة عمل مع شركة.</td><td>ليس وحده.</td></tr>
<tr><td><strong>تصريح العمل والإقامة</strong></td><td>يتعلق بالوضع القانوني للأجنبي في إسبانيا.</td><td>هو جزء أساسي من المسار، حسب الحالة.</td></tr>
<tr><td><strong>الاعتراف أو تبديل الرخصة</strong></td><td>يحدد وضع رخصة القيادة الأجنبية في إسبانيا.</td><td>لا يغني عن باقي الشروط.</td></tr>
</table>
<p class="important">وجود Code 95 لا يحول رخصة القيادة المغربية تلقائيًا إلى رخصة إسبانية، ولا يمنح وحده حق الإقامة أو العمل في إسبانيا.</p>
</div>

<div class="card warning">
<h2>3. هل يمكن لأي سائق مغربي الذهاب إلى بولندا أو ليتوانيا وأخذ Code 95 ثم العمل في إسبانيا؟</h2>
<p><strong>لا يصح نشر هذه الفكرة بهذه الصورة المبسطة:</strong> «اذهب كسائح إلى بولندا أو ليتوانيا، خذ Code 95، وبعدها يمكنك العمل في إسبانيا».</p>
<p>بالنسبة للسائقين من خارج الاتحاد الأوروبي، يجب معرفة الأساس القانوني للحصول على التأهيل ووضع السائق والشركة والتصريح المطلوب، وليس النظر إلى بطاقة Code 95 وحدها.</p>
<div class="note">
<strong>المعنى العملي:</strong> وجود تدريب أو إجراء لإصدار تأهيل مهني في دولة أوروبية لا يعني أن كل شخص، مهما كان وضعه القانوني في تلك الدولة، يستطيع الحصول عليه ثم استعماله كبديل عن تصريح العمل أو الإقامة في إسبانيا.
</div>
</div>

<div class="card">
<h2>4. ماذا عن ليتوانيا؟</h2>
<p>توجد في ليتوانيا إجراءات رسمية لتأهيل السائقين المهنيين وإصدار بطاقة تأهيل السائق DQC. ويمكن أن تتضمن البطاقة رمز الاتحاد الأوروبي 95.</p>
<p>وتوضح الجهة الليتوانية Regitra أن بطاقة DQC مرتبطة بتأهيل سائقي فئات C1 وC1E وC وCE وD1 وD1E وD وDE للنقل التجاري، وأن بطاقات DQC صالحة في دول الاتحاد الأوروبي والمنطقة الاقتصادية الأوروبية.</p>
<p>لكن يجب التفريق بين <strong>الاعتراف بالتأهيل المهني</strong> وبين <strong>حق الشخص في الإقامة والعمل</strong>. صلاحية DQC في الاتحاد الأوروبي لا تعني أنها تصريح عمل إسباني.</p>
<p><a href="https://regitra.lt/en/services/driving-licences/driver-qualification-cards" target="_blank">المصدر الرسمي: Regitra Lithuania</a></p>
</div>

<div class="card">
<h2>5. وماذا عن بولندا؟</h2>
<p>المبدأ الذي يجب فهمه هو نفسه: يجب معرفة كيف حصل السائق على التأهيل، وما هو وضعه القانوني، وما هي العلاقة بينه وبين الشركة أو جهة العمل التي يستند إليها مسار التأهيل.</p>
<p>لذلك عندما يقول شخص: «لدي Code 95 بولندي، إذن أستطيع العمل في إسبانيا»، يجب طرح أسئلة واضحة:</p>
<ul>
<li>بأي أساس قانوني حصل على التأهيل؟</li>
<li>ما هي رخصة القيادة التي يحملها؟</li>
<li>هل التأهيل ساري ومناسب لنوع العمل؟</li>
<li>ما هو وضعه القانوني في الدولة التي أصدرت التأهيل؟</li>
<li>هل لديه الحق القانوني في العمل والإقامة في إسبانيا؟</li>
</ul>
<p class="important">لذلك لا ينبغي اعتبار عبارة «Code 95 بولندي = عمل مضمون في إسبانيا» قاعدة عامة.</p>
</div>

<div class="card success">
<h2>6. إذا كان لدي عقد عمل من شركة إسبانية</h2>
<p>إذا وجدت شركة إسبانية حقيقية تريد توظيف سائق مغربي، فإن عقد العمل يمكن أن يكون جزءًا من المسار القانوني للعمل في إسبانيا.</p>
<p>لكن <strong>عقد العمل ليس هو نفسه تصريح العمل والإقامة</strong>.</p>
<p>يجب النظر إلى الملف كاملًا: وضع السائق كمواطن من خارج الاتحاد الأوروبي، إجراءات صاحب العمل، تصريح العمل والإقامة عند انطباقه، رخصة القيادة، والتأهيل المهني المطلوب.</p>
<div class="note">
<strong>مثال:</strong> سائق مغربي لديه C+E مغربية وعقد من شركة إسبانية. لا يكفي أن يقول «سأضيف Code 95 وانتهى الأمر». يجب معرفة الطريق القانوني الذي ستسلكه الشركة لتوظيفه، وكيف سيتم إثبات التأهيل المهني، وما وضع رخصته المغربية في إسبانيا.
</div>
</div>

<div class="card">
<h2>7. ماذا عن عبارة «لدي 6 أشهر بالرخصة المغربية»؟</h2>
<p>هذه النقطة كثيرًا ما تختلط مع موضوع Code 95.</p>
<p>صلاحية استعمال رخصة قيادة أجنبية في إسبانيا تخضع لشروط وقواعد إسبانية خاصة بالرخص الأجنبية والإقامة العادية.</p>
<p>وتوضح DGT أن الرخصة الأجنبية من الدول التي لديها اتفاقية، عند استيفاء الشروط، تكون صالحة بحد أقصى لمدة ستة أشهر من اكتساب <strong>الإقامة العادية في إسبانيا</strong>.</p>
<p class="important">لذلك لا نقول إن الستة أشهر تبدأ من تاريخ توقيع عقد العمل، ولا من تاريخ الحصول على Code 95.</p>
<p><a href="https://www.dgt.es/nuestros-servicios/permisos-de-conducir/permisos-extranjeros-y-de-fuerzas-y-cuerpos-de-seguridad/conducir-con-un-permiso-extranjero/" target="_blank">DGT — القيادة برخصة أجنبية</a></p>
</div>

<div class="card">
<h2>8. وماذا عن تبديل الرخصة المغربية إلى الإسبانية؟</h2>
<p>إسبانيا والمغرب لديهما اتفاقية لتبادل رخص القيادة، لكن الإجراء والشروط يختلفان حسب فئة الرخصة.</p>
<p>وتوضح DGT أن المغرب من الدول التي لديها اتفاقية لتبادل الرخص. وبالنسبة للرخص التي تشمل فئات <strong>C وD</strong>، أي الشاحنات والحافلات، توجد اختبارات إضافية حسب الجدول الرسمي الحالي.</p>
<p>كما توجد شروط تتعلق بتاريخ الحصول على الرخصة مقارنة بتاريخ اكتساب الإقامة القانونية في إسبانيا.</p>
<p class="important">لذلك لا ينبغي القول للسائق إن تبديل الرخصة المغربية الثقيلة إلى الإسبانية يتم تلقائيًا دون اختبارات أو شروط.</p>
<p><a href="https://www.dgt.es/nuestros-servicios/permisos-de-conducir/permisos-extranjeros-y-de-fuerzas-y-cuerpos-de-seguridad/canjes-de-permisos/paises-con-convenio-de-canjes/" target="_blank">المصدر الرسمي DGT — اتفاقية المغرب وشروط التبديل</a></p>
</div>

<div class="card warning">
<h2>9. ثلاثة أمثلة عملية</h2>

<h3>الحالة الأولى: رخصة C+E مغربية فقط</h3>
<p>السائق لديه رخصة C+E مغربية سارية.</p>
<p><strong>هذا يثبت فئة القيادة، لكنه لا يعني تلقائيًا أن جميع متطلبات القيادة المهنية والعمل في إسبانيا قد اكتملت.</strong></p>

<h3>الحالة الثانية: C+E مغربية + Code 95 أوروبي</h3>
<p>السائق لديه C+E مغربية وحصل على DQC أو Code 95 في دولة أوروبية.</p>
<p><strong>وجود التأهيل المهني لا يعني تلقائيًا وجود تصريح عمل أو إقامة في إسبانيا.</strong></p>

<h3>الحالة الثالثة: C+E + Code 95 + شركة إسبانية</h3>
<p>السائق لديه رخصة مناسبة، وتأهيل مهني، وشركة إسبانية حقيقية تريد توظيفه.</p>
<p><strong>هنا يجب دراسة الملف كاملًا:</strong> التوظيف، والهجرة، وتصريح العمل والإقامة، ورخصة القيادة، والتأهيل المهني.</p>
</div>

<div class="card info">
<h2>10. ما الذي لا يعنيه Code 95؟</h2>
<ul>
<li>لا يعني أنه تأشيرة إلى إسبانيا.</li>
<li>لا يعني أنه تصريح إقامة إسباني.</li>
<li>لا يعني أنه تصريح عمل إسباني.</li>
<li>لا يحول رخصة القيادة المغربية تلقائيًا إلى رخصة إسبانية.</li>
<li>لا يضمن الحصول على عقد عمل.</li>
<li>لا يضمن قبول السائق لدى شركة إسبانية.</li>
<li>لا يسمح بتجاوز قوانين الهجرة أو شروط الاعتراف بالرخصة.</li>
</ul>
</div>

<div class="card">
<h2>11. كيف يتحقق السائق قبل أن يدفع المال؟</h2>
<p>إذا عرض عليك شخص خدمة باسم «Code 95 بولندا» أو «Code 95 ليتوانيا ثم إسبانيا»، لا تكتفِ بصورة البطاقة أو بوعد شفهي.</p>
<p>اطلب معرفة:</p>
<ol>
<li>اسم الجهة الرسمية أو مركز التدريب الذي سيصدر التأهيل.</li>
<li>نوع التأهيل: تأهيل أولي أم تدريب دوري؟</li>
<li>ما هي رخصة القيادة المطلوبة؟</li>
<li>ما هو الأساس القانوني لإصدار التأهيل لشخص من خارج الاتحاد الأوروبي؟</li>
<li>ما هو الوضع القانوني للسائق في الدولة التي سيحصل فيها على التأهيل؟</li>
<li>هل توجد شركة مستخدمة أو تصريح عمل مرتبط بالمسار عندما يكون ذلك مطلوبًا؟</li>
<li>ما هي الخطوة القانونية بعد ذلك للعمل في إسبانيا؟</li>
</ol>
<div class="note">
<strong>إذا كان الجواب الوحيد هو «ادفع المال، خذ Code 95، وبعدها إسبانيا مضمونة»، فهذه ليست معلومات قانونية كافية لاتخاذ قرار.</strong>
</div>
</div>

<div class="card success">
<h2>12. الخلاصة للسائق المغربي</h2>
<p><strong>رخصة القيادة، Code 95، عقد العمل، وتصريح العمل والإقامة ليست وثيقة واحدة.</strong></p>
<p>قد تكون هذه العناصر مرتبطة ببعضها في المسار المهني، لكنها لا تلغي بعضها بعضًا.</p>
<p>إذا كنت سائقًا مغربيًا وتفكر في العمل في إسبانيا، فاسأل عن الملف كاملًا:</p>
<ul>
<li>ما هي رخصة القيادة والفئة التي أملكها؟</li>
<li>أين وكيف سأحصل على التأهيل المهني؟</li>
<li>هل أحتاج إلى Code 95 أو DQC؟</li>
<li>من هي الشركة التي ستوظفني؟</li>
<li>ما هو مسار تصريح العمل والإقامة؟</li>
<li>ما وضع رخصتي المغربية في إسبانيا؟</li>
<li>هل أحتاج إلى تبديلها أو إجراء اختبارات؟</li>
</ul>
<p class="important">بهذه الطريقة يستطيع السائق أن يميز بين المسار القانوني الحقيقي وبين الوعود التجارية غير الواضحة.</p>
</div>

