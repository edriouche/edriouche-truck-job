<h1>⚖️ 🇪🇸 Législation et règles pour les conducteurs professionnels en Espagne</h1>
<p>Guide pratique pour les conducteurs professionnels du transport routier afin d’éviter les infractions</p>
</header>

<div class="container">

<div class="warning">
<strong>⚠️ Avis juridique important :</strong>
Ce guide est fourni à titre éducatif et informatif pour les conducteurs professionnels. Il ne remplace pas la consultation des textes officiels en vigueur ni les conseils d’un professionnel en cas de situation particulière.
Les règles européennes et nationales peuvent évoluer et certaines exceptions s’appliquent à certains types de transport, de véhicules et d’opérations.
</div>

<div class="card">
<h2>🇪🇺 1. Temps de conduite, pauses et repos</h2>

<div class="article">
<strong>Conduite quotidienne — article 6 :</strong>
La durée maximale habituelle de conduite est de <strong>9 heures par jour</strong>, avec possibilité de l’étendre à <strong>10 heures deux fois par semaine</strong>.
</div>

<div class="article">
<strong>Conduite hebdomadaire :</strong>
La durée de conduite ne doit pas dépasser <strong>56 heures par semaine</strong>.
</div>

<div class="article">
<strong>Sur deux semaines consécutives :</strong>
La durée totale de conduite ne doit pas dépasser <strong>90 heures</strong>.
</div>

<div class="article">
<strong>Pause après la conduite — article 7 :</strong>
Après un total de <strong>4 heures et 30 minutes</strong> de conduite, une pause d’au moins <strong>45 minutes</strong> doit être prise, sauf si le conducteur commence une période de repos.
La pause peut être fractionnée, conformément aux conditions légales, en <strong>15 minutes puis 30 minutes</strong>.
</div>

<div class="article">
<strong>Repos quotidien — article 8 :</strong>
Une période de repos quotidien régulière d’au moins <strong>11 heures</strong> doit être prise.
Dans les cas autorisés par la loi, un repos quotidien réduit d’au moins <strong>9 heures</strong> peut être pris, dans le respect des limites et des compensations prévues.
</div>

<div class="article">
<strong>Repos quotidien fractionné :</strong>
Conformément aux conditions légales, le repos quotidien régulier peut être fractionné en une première période d’au moins <strong>3 heures</strong> et une seconde période d’au moins <strong>9 heures</strong>.
</div>

<div class="article">
<strong>Repos hebdomadaire :</strong>
Les règles relatives au repos hebdomadaire régulier et réduit ainsi qu’à sa compensation doivent être respectées conformément à l’article 8 du règlement européen.
Le repos hebdomadaire régulier est normalement d’au moins <strong>45 heures</strong>. Il peut être réduit dans les cas autorisés, avec compensation conformément à la loi.
</div>

<div class="info">
<strong>📌 Règle importante :</strong>
Le conducteur doit organiser son travail de manière à respecter les temps de conduite, les pauses et les repos. L’entreprise ne doit pas faire pression sur lui pour qu’il exécute un programme contraire aux règles.
</div>

</div>

<div class="card">
<h2>🧭 2. Tachygraphe</h2>

<div class="article">
<strong>Reglamento (UE) 165/2014:</strong>
Le tachygraphe et son utilisation permettent d’enregistrer les activités du conducteur ainsi que les données relatives à la conduite, aux repos et aux autres activités.
</div>

<div class="article">
<strong>🚨 Interdiction de la manipulation :</strong>
Il est interdit de manipuler le tachygraphe ou ses données, ou d’utiliser des moyens visant à modifier ou dissimuler l’activité réelle du conducteur.
</div>

<div class="article">
<strong>📋 Lors d’un contrôle :</strong>
Les données, enregistrements et documents requis doivent être disponibles conformément aux règles applicables au voyage, au véhicule et à la période contrôlée.
</div>

<div class="article">
<strong>🌍 À partir du 1er juillet 2026 :</strong>
Dans le transport international ou les opérations de cabotage, le tachygraphe est également obligatoire pour les véhicules destinés au transport de marchandises dont la masse maximale autorisée dépasse <strong>2,5 tonnes</strong>, selon les conditions prévues par les règles européennes.
</div>

<div class="article">
<strong>🛰️ Tachygraphe intelligent :</strong>
Des règles européennes prévoient une mise en place progressive du tachygraphe intelligent, notamment pour le transport international. Il faut donc vérifier le type de véhicule, sa date d’immatriculation et le type d’opération.
</div>

</div>

<div class="card">
<h2>🚨 3. Infractions en Espagne</h2>

<div class="article">
<strong>LOTT — Ley 16/1987:</strong>
En Espagne, la Ley 16/1987 réglemente le transport routier, le système de contrôle et le régime des sanctions. Ses articles <strong>140 et 141</strong> comprennent des classifications d’infractions, notamment celles liées aux temps de conduite et de repos et au tachygraphe.
</div>

<div class="article">
<strong>⚠️ La gravité de l’infraction est importante :</strong>
Il ne suffit pas de dire qu’il s’agit d’une « infraction au tachygraphe » ou d’une « infraction relative au repos », car la classification et la sanction dépendent du type d’infraction, des faits et de la réglementation en vigueur.
</div>

<div class="article">
<strong>❗ Ne vous fiez pas à un ancien montant d’amende :</strong>
Nous n’indiquons pas de montants fixes d’amendes sur cette page, car les règles et les classifications peuvent évoluer et le résultat peut varier selon le type d’infraction et les circonstances juridiques.
</div>

</div>

<div class="card">
<h2>🎓 4. CAP — Qualification du conducteur professionnel en Espagne</h2>

<p>
Le certificat <strong>CAP — Certificado de Aptitud Profesional</strong> est lié à la qualification initiale et à la formation continue des conducteurs professionnels du transport routier, conformément aux règles espagnoles et européennes applicables.
</p>

<div class="article">
<strong>Real Decreto 284/2021 :</strong>
Il réglemente en Espagne la qualification initiale et la formation continue des conducteurs professionnels concernés par le transport routier.
</div>

<div class="article">
<strong>📅 Mise à jour importante en 2026 :</strong>
Le <strong>Real Decreto 487/2026</strong> a été publié pour modifier le Real Decreto 284/2021.
Certaines modifications publiées en juin 2026 entrent en vigueur le <strong>18 septembre 2026</strong>. Il faut donc distinguer les règles actuellement en vigueur des modifications qui ne sont pas encore entrées en vigueur.
</div>

<div class="info">
<strong>📌 Pour le conducteur venant travailler en Espagne :</strong>
Les exigences du CAP dépendent de la situation du conducteur, du type de transport, de son permis de conduire, de sa qualification et des règles qui lui sont applicables. Il ne faut pas supposer que la possession d’un permis de conduire étranger signifie automatiquement que les exigences du CAP sont remplies.
</div>

</div>

<div class="card">
<h2>🚛 5. Avant de prendre la route</h2>

<ul>
<li>✅ Vérifiez le permis de conduire et les documents requis.</li>
<li>✅ Vérifiez les exigences du CAP si elles vous sont applicables.</li>
<li>✅ Vérifiez le tachygraphe et la manière correcte d’enregistrer votre activité.</li>
<li>✅ Revoyez les temps de conduite, les pauses et les périodes de repos.</li>
<li>✅ Vérifiez l’état et la sécurité du véhicule.</li>
<li>✅ Assurez-vous que la charge est correctement sécurisée.</li>
<li>✅ Vérifiez les documents relatifs à la marchandise et au transport.</li>
<li>✅ Pour le transport de marchandises dangereuses, vérifiez les exigences ADR.</li>
<li>✅ Conservez avec vous les documents et enregistrements requis pendant le voyage.</li>
</ul>

</div>

<div class="card">
<h2>🔴 Erreurs à éviter</h2>

<ul>
<li>❌ Dépasser la limite légale de conduite.</li>
<li>❌ Ne pas respecter la pause de 45 minutes après 4 heures et demie de conduite, conformément aux règles.</li>
<li>❌ Réduire les périodes de repos sans base légale.</li>
<li>❌ Enregistrer incorrectement l’activité dans le tachygraphe.</li>
<li>❌ Utiliser une carte de conducteur qui n’est pas au nom du conducteur.</li>
<li>❌ Utiliser des moyens pour manipuler le tachygraphe.</li>
<li>❌ Négliger les documents requis.</li>
<li>❌ Ignorer les règles relatives au chargement et à la sécurité.</li>
</ul>

</div>

