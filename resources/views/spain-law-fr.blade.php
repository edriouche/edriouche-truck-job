<div class="card">
<h2>🎓 4. CAP — Qualification du conducteur professionnel en Espagne</h2>

<p>
Le certificat <strong>CAP — Certificado de Aptitud Profesional</strong> est lié à la qualification initiale et à la formation continue des conducteurs professionnels du transport routier, conformément aux règles espagnoles et européennes applicables.
</p>

<div class="article">
<strong>Real Decreto 284/2021 :</strong>
Il réglemente en Espagne la qualification initiale et la formation continue des conducteurs professionnels concernés par le transport routier.
</div>

<div class="article">
<strong>📅 Mise à jour importante en 2026 :</strong>
Le <strong>Real Decreto 487/2026</strong> a été publié pour modifier le Real Decreto 284/2021.
Certaines modifications publiées en juin 2026 entrent en vigueur le <strong>18 septembre 2026</strong>. Il faut donc distinguer les règles actuellement en vigueur des modifications qui ne sont pas encore entrées en vigueur.
</div>

<div class="info">
<strong>📌 Pour le conducteur venant travailler en Espagne :</strong>
Les exigences du CAP dépendent de la situation du conducteur, du type de transport, de son permis de conduire, de sa qualification et des règles qui lui sont applicables. Il ne faut pas supposer que la possession d’un permis de conduire étranger signifie automatiquement que les exigences du CAP sont remplies.
</div>

</div>

<div class="card">
<h2>🚛 5. Avant de prendre la route</h2>

<ul>
<li>✅ Vérifiez le permis de conduire et les documents requis.</li>
<li>✅ Vérifiez les exigences du CAP si elles vous sont applicables.</li>
<li>✅ Vérifiez le tachygraphe et la manière correcte d’enregistrer votre activité.</li>
<li>✅ Revoyez les temps de conduite, les pauses et les périodes de repos.</li>
<li>✅ Vérifiez l’état et la sécurité du véhicule.</li>
<li>✅ Assurez-vous que la charge est correctement sécurisée.</li>
<li>✅ Vérifiez les documents relatifs à la marchandise et au transport.</li>
<li>✅ Pour le transport de marchandises dangereuses, vérifiez les exigences ADR.</li>
<li>✅ Conservez avec vous les documents et enregistrements requis pendant le voyage.</li>
</ul>

</div>

<div class="card">
<h2>🔴 Erreurs à éviter</h2>

<ul>
<li>❌ Dépasser la limite légale de conduite.</li>
<li>❌ Ne pas respecter la pause de 45 minutes après 4 heures et demie de conduite, conformément aux règles.</li>
<li>❌ Réduire les périodes de repos sans base légale.</li>
<li>❌ Enregistrer incorrectement l’activité dans le tachygraphe.</li>
<li>❌ Utiliser une carte de conducteur qui n’est pas au nom du conducteur.</li>
<li>❌ Utiliser des moyens pour manipuler le tachygraphe.</li>
<li>❌ Négliger les documents requis.</li>
<li>❌ Ignorer les règles relatives au chargement et à la sécurité.</li>
</ul>

