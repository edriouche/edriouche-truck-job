<div class="container">
<section class="card">
<h2>1. Prepare your documents</h2>
<ul>
<li>Keep your driving licence valid for the vehicle categories you intend to drive.</li>
<li>Prepare your professional driver card or qualification documents, where applicable.</li>
<li>Keep your passport, CV, employment records and relevant certificates up to date.</li>
<li>Check whether the destination country requires additional qualifications or documents.</li>
</ul>
</section>
<section class="card">
<h2>2. Understand the requirements before travelling</h2>
<p>Driving licence recognition, professional qualifications, residence permission and work authorisation are separate matters. Requirements depend on your nationality, documents, employer and destination country.</p>
<p>Before accepting a job abroad, verify the legal procedure with the competent official authorities and ask the employer to explain which documents you must obtain.</p>
</section>
<section class="card">
<h2>3. Apply directly to employers</h2>
<ul>
<li>Use the employer's official website or verified recruitment contact.</li>
<li>Send a clear CV describing your actual experience, licence categories and languages.</li>
<li>Ask for the job location, duties, salary, working hours and contract terms in writing.</li>
<li>Keep copies of applications and all correspondence.</li>
</ul>
</section>
<section class="card warning">
<h2>4. Protect yourself from false promises</h2>
<ul>
<li>Be cautious of anyone promising a guaranteed visa, job or work permit in exchange for money.</li>
<li>Verify the company and the identity of the person contacting you.</li>
<li>Read every contract and fee agreement before signing or paying.</li>
<li>Do not hand over original documents unless the relevant official procedure requires them and you understand the process.</li>
</ul>
<p><strong>A company appearing on a job website does not necessarily have a current vacancy or endorse an intermediary.</strong></p>
</section>
<section class="card">
<h2>5. Safety and professionalism</h2>
<ul>
<li>Respect driving-time, rest-period and road-safety rules applicable to your work.</li>
<li>Inspect the vehicle before departure and report defects promptly.</li>
<li>Secure cargo correctly and follow the employer's safety procedures.</li>
<li>Never drive when tired or when the vehicle is unsafe.</li>
</ul>
</section>
