<h1>⚖️ 🇪🇸 Legislación y normas para conductores profesionales en España</h1>
<p>Guía práctica para conductores profesionales de transporte por carretera para evitar infracciones</p>
</header>

<div class="container">

<div class="warning">
<strong>⚠️ Aviso legal importante:</strong>
Esta guía tiene carácter educativo e informativo para conductores profesionales y no sustituye la consulta de los textos oficiales vigentes ni el asesoramiento de un profesional cuando exista un caso particular.
Las normas europeas y nacionales pueden cambiar y existen excepciones específicas para determinados tipos de transporte, vehículos y operaciones.
</div>

<div class="card">
<h2>🇪🇺 1. Tiempos de conducción, pausas y descansos</h2>

<div class="article">
<strong>Conducción diaria — artículo 6:</strong>
El tiempo máximo habitual de conducción es de <strong>9 horas al día</strong> y puede ampliarse a <strong>10 horas dos veces por semana</strong>.
</div>

<div class="article">
<strong>Conducción semanal:</strong>
La conducción no puede superar las <strong>56 horas por semana</strong>.
</div>

<div class="article">
<strong>Durante dos semanas consecutivas:</strong>
El tiempo total de conducción no puede superar las <strong>90 horas</strong>.
</div>

<div class="article">
<strong>Pausa después de la conducción — artículo 7:</strong>
Después de un período de conducción acumulado de <strong>4 horas y 30 minutos</strong>, debe realizarse una pausa de al menos <strong>45 minutos</strong>, salvo que comience un período de descanso.
La pausa puede dividirse, conforme a las condiciones legales, en <strong>15 minutos y después 30 minutos</strong>.
</div>

<div class="article">
<strong>Descanso diario — artículo 8:</strong>
Debe disfrutarse de un período de descanso diario regular de al menos <strong>11 horas</strong>.
En los casos permitidos por la normativa, puede realizarse un descanso diario reducido de al menos <strong>9 horas</strong>, respetando las limitaciones y compensaciones establecidas.
</div>

<div class="article">
<strong>Descanso diario fraccionado:</strong>
Conforme a las condiciones legales, el descanso diario regular puede dividirse en un primer período de al menos <strong>3 horas</strong> y un segundo período de al menos <strong>9 horas</strong>.
</div>

<div class="article">
<strong>Descanso semanal:</strong>
Deben respetarse las normas relativas al descanso semanal regular y reducido, así como su compensación, de acuerdo con el artículo 8 del reglamento europeo.
El descanso semanal regular es normalmente de <strong>al menos 45 horas</strong> y puede reducirse en los casos permitidos, con la compensación prevista por la normativa.
</div>

<div class="info">
<strong>📌 Regla importante:</strong>
El conductor debe organizar su trabajo de manera que pueda respetar los tiempos de conducción, las pausas y los descansos. La empresa no debe presionarlo para realizar un servicio que incumpla las normas.
</div>

</div>

<div class="card">
<h2>🧭 2. Tacógrafo</h2>

<div class="article">
<strong>Reglamento (UE) 165/2014:</strong>
Regula el tacógrafo, su utilización y el registro de las actividades del conductor, así como los datos relacionados con la conducción, los descansos y otras actividades.
</div>

<div class="article">
<strong>🚨 Prohibición de manipulación:</strong>
Está prohibido manipular el tacógrafo o sus datos, así como utilizar medios destinados a modificar u ocultar la actividad real del conductor.
</div>

<div class="article">
<strong>📋 Durante una inspección:</strong>
Los datos, registros y documentos exigidos deben estar disponibles conforme a las normas aplicables al viaje, al vehículo y al período que se esté comprobando.
</div>

<div class="article">
<strong>🌍 A partir del 1 de julio de 2026:</strong>
En el transporte internacional o en operaciones de cabotaje, el tacógrafo también es obligatorio para determinados vehículos destinados al transporte de mercancías cuya masa máxima autorizada supere las <strong>2,5 toneladas</strong>, conforme a las condiciones establecidas por las normas europeas.
</div>

<div class="article">
<strong>🛰️ Tacógrafo inteligente:</strong>
Existen normas europeas progresivas para equipar los vehículos con tacógrafo inteligente, especialmente en el transporte internacional. Por ello, deben comprobarse el tipo de vehículo, su fecha de matriculación y el tipo de operación.
</div>

</div>

<div class="card">
<h2>🚨 3. Infracciones en España</h2>

<div class="article">
<strong>LOTT — Ley 16/1987:</strong>
En España, la Ley 16/1987 regula el transporte terrestre, el sistema de control y el régimen sancionador. Sus artículos <strong>140 y 141</strong> incluyen clasificaciones de infracciones, entre ellas las relacionadas con los tiempos de conducción y descanso y con el tacógrafo.
</div>

<div class="article">
<strong>⚠️ La gravedad de la infracción es importante:</strong>
No basta con decir que se trata de una "infracción del tacógrafo" o una "infracción de descanso", porque la clasificación y la sanción dependen del tipo de infracción, de los hechos y de la normativa vigente.
</div>

<div class="article">
<strong>❗ No te bases en una cuantía de multa antigua:</strong>
No indicamos en esta página cantidades fijas de multas porque las normas y las clasificaciones pueden cambiar y el resultado puede variar según el tipo de infracción y las circunstancias legales.
</div>

</div>

<div class="card">
<h2>🎓 4. CAP — Cualificación del conductor profesional en España</h2>

<p>
El certificado <strong>CAP — Certificado de Aptitud Profesional</strong> está relacionado con la cualificación inicial y la formación continua de los conductores profesionales de transporte por carretera, de acuerdo con las normas españolas y europeas aplicables.
</p>

<div class="article">
<strong>Real Decreto 284/2021:</strong>
Regula en España la cualificación inicial y la formación continua de los conductores profesionales sujetos a estas normas.
</div>

<div class="article">
<strong>📅 Actualización importante en 2026:</strong>
Se publicó el <strong>Real Decreto 487/2026</strong> para modificar el Real Decreto 284/2021.
Algunas modificaciones publicadas en junio de 2026 entran en vigor el <strong>18 de septiembre de 2026</strong>. Por ello, es importante distinguir entre las normas actualmente vigentes y las modificaciones que todavía no han entrado en vigor.
</div>

<div class="info">
<strong>📌 Para el conductor que viene a trabajar a España:</strong>
Los requisitos del CAP dependen de la situación del conductor, del tipo de transporte, de su permiso de conducción, de su cualificación y de las normas que le sean aplicables. No debes suponer que tener un permiso de conducción extranjero significa automáticamente cumplir los requisitos del CAP.
</div>

</div>

<div class="card">
<h2>🚛 5. Antes de iniciar el viaje</h2>

<ul>
<li>✅ Comprueba el permiso de conducción y los documentos necesarios.</li>
<li>✅ Comprueba los requisitos del CAP si son aplicables a tu caso.</li>
<li>✅ Comprueba el tacógrafo y la forma correcta de registrar tu actividad.</li>
<li>✅ Revisa los tiempos de conducción, pausas y descansos.</li>
<li>✅ Comprueba el estado y la seguridad del vehículo.</li>
<li>✅ Asegúrate de que la carga está correctamente asegurada.</li>
<li>✅ Comprueba los documentos de la mercancía y del transporte.</li>
<li>✅ En el transporte de mercancías peligrosas, comprueba los requisitos ADR.</li>
<li>✅ Lleva contigo los documentos y registros exigidos durante el viaje.</li>
</ul>

</div>

<div class="card">
<h2>🔴 Errores que debes evitar</h2>

<ul>
<li>❌ Superar el límite legal de conducción.</li>
<li>❌ No respetar la pausa de 45 minutos después de 4 horas y media de conducción, según las normas.</li>
<li>❌ Reducir los períodos de descanso sin una base legal.</li>
<li>❌ Registrar incorrectamente la actividad en el tacógrafo.</li>
<li>❌ Utilizar una tarjeta de conductor que no esté a nombre del propio conductor.</li>
<li>❌ Utilizar medios para manipular el tacógrafo.</li>
<li>❌ Descuidar los documentos exigidos.</li>
<li>❌ Ignorar las normas de carga y seguridad.</li>
</ul>

