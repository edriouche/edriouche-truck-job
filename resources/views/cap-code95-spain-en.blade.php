<h1>CAP / Code 95 and Working in Spain</h1>
<p>Practical information for Moroccan professional drivers</p>
</header>
<div class="container">
<div class="card warning">
<h2>Why this guide matters</h2>
<p>Drivers may hear that obtaining CAP / Code 95 in Poland or Lithuania automatically allows them to work in Spain. Do not rely on this assumption without checking the legal requirements for your situation.</p>
<p>A driving licence, professional qualification, employment contract, and residence and work authorisation are different things.</p>
</div>
<div class="card">
<h2>1. What is Code 95?</h2>
<p>Code 95 relates to professional qualification requirements for drivers transporting goods or passengers where the relevant rules apply. Depending on the country and procedure, the qualification may be evidenced on a driving licence or by a Driver Qualification Card (DQC).</p>
<p><strong>Code 95 is not a driving licence and is not a residence or work permit.</strong></p>
</div>
<div class="card">
<h2>2. Understand the documents</h2>
<ul>
<li><strong>C or CE driving licence:</strong> identifies the vehicle categories you are authorised to drive.</li>
<li><strong>Code 95 / DQC:</strong> evidences professional qualification where required.</li>
<li><strong>Employment contract:</strong> documents an employment relationship, but does not by itself grant immigration status.</li>
<li><strong>Residence and work authorisation:</strong> determines whether a non-EU national may legally reside and work in Spain in their particular circumstances.</li>
</ul>
<p><strong>Code 95 does not automatically convert a Moroccan driving licence into a Spanish licence or grant permission to work in Spain.</strong></p>
</div>
<div class="card warning">
<h2>3. Before paying an intermediary</h2>
<p>Do not assume that travelling to Poland or Lithuania as a tourist, obtaining a qualification, and then going to work in Spain is automatically lawful or possible for every driver.</p>
<ul>
<li>Ask which authority issues the qualification and on what legal basis.</li>
<li>Check that your driving licence and professional qualification are valid for the intended job.</li>
<li>Confirm the residence and work authorisation required for Spain.</li>
<li>Verify the employer, written contract, fees, refund terms, and responsibilities.</li>
</ul>
<p><strong>“Code 95 = guaranteed job in Spain” is not a reliable general rule.</strong></p>
</div>
<div class="card">
<h2>4. Check official information</h2>
<p>For information about Lithuanian Driver Qualification Cards, consult the official Regitra website:</p>
<p><a href="https://regitra.lt/en/services/driving-licences/driver-qualification-cards" target="_blank" rel="noopener noreferrer">Regitra — Driver Qualification Cards</a></p>
<p>Check the applicable Spanish requirements with the competent official authorities for your individual circumstances.</p>
</div>
<div class="card warning">
<h2>Protect yourself from false promises</h2>
<p>Do not pay for a guaranteed visa, job, or work permit without verifying the employer, legal procedure, written terms, and official requirements. A company listed on this website does not necessarily have current vacancies or endorse any intermediary.</p>
