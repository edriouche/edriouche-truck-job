<h1>🧭 بوصلة السائق المغربي في أوروبا</h1>

<div class="box">
<strong>دليل عملي للسائق الذي يعرف التاكوغراف القديم (الورقي) ويريد فهم العمل القانوني في أوروبا.</strong><br>
هذا الدليل يشرح الفرق بين التاكوغراف التناظري والرقمي، وكيف تسجل القيادة والعمل والراحة، وما الذي يجب أن يكون معك أثناء التفتيش.
</div>

<h2>1️⃣ أولاً: ما هو التاكوغراف؟</h2>
<p>
التاكوغراف جهاز يسجل نشاط الشاحنة والسائق، خصوصاً وقت القيادة وفترات الراحة والعمل والتوفر.
في التاكوغراف القديم يستعمل السائق <strong>قرصاً ورقياً</strong>، بينما التاكوغراف الرقمي يستعمل <strong>بطاقة سائق شخصية</strong>.
</p>

<div class="warn">
<strong>مهم للسائق المغربي:</strong>
لا يعني كونك معتاداً على التاكوغراف الورقي في المغرب أن أي شاحنة في أوروبا يمكن تشغيلها بالطريقة نفسها.
نوع التاكوغراف الذي يجب استعماله مرتبط بالشاحنة، تاريخها، نوع النقل والقواعد الأوروبية المطبقة عليها.
</div>

<h2>2️⃣ التاكوغراف القديم: القرص الورقي</h2>
<p>إذا كنت تعمل على شاحنة مجهزة قانونياً بتاكوغراف تناظري، فالقرص الورقي هو سجل نشاطك.</p>

<ul>
<li>اكتب بياناتك المطلوبة على القرص.</li>
<li>سجل مكان وتاريخ بداية العمل حسب الجهاز والقواعد المطبقة.</li>
<li>ضع القرص في الجهاز قبل القيادة.</li>
<li>تأكد من ضبط الوقت الصحيح.</li>
<li>عند تغيير النشاط، يجب أن يعكس القرص النشاط الحقيقي.</li>
<li>احتفظ بالبيانات والسجلات المطلوبة للتفتيش.</li>
</ul>

<div class="good">
<strong>قاعدة ذهبية:</strong> لا تستعمل القرص كأنه مجرد ورقة للقيادة فقط. يجب أن يعكس نشاطك الحقيقي.
</div>

<h2>3️⃣ ماذا أسجل أثناء يوم العمل؟</h2>

<table>
<tr><th>النشاط</th><th>ماذا يعني؟</th></tr>
<tr><td>🚛 القيادة</td><td>عندما تكون الشاحنة تتحرك وأنت تقود.</td></tr>
<tr><td>🔧 عمل آخر</td><td>تحميل، تفريغ، فحص الشاحنة، أعمال مهنية وغيرها.</td></tr>
<tr><td>⏳ التوفر</td><td>فترة تكون فيها متاحاً للعمل ولكن لا تقوم بعمل فعلي.</td></tr>
<tr><td>☕ استراحة</td><td>فترة لا تقوم فيها بالقيادة أو عمل آخر وتستعملها للاستراحة.</td></tr>
<tr><td>😴 راحة</td><td>فترة تستطيع فيها التصرف بحرية في وقتك حسب شروط الراحة القانونية.</td></tr>
</table>

<h2>4️⃣ قاعدة 4 ساعات و30 دقيقة</h2>

<div class="box">
بعد مدة قيادة لا تتجاوز <strong>4 ساعات و30 دقيقة</strong>، يجب أخذ استراحة لا تقل عن <strong>45 دقيقة</strong>، ما لم تبدأ فترة راحة.
</div>

<p>
يمكن تقسيم الـ45 دقيقة إلى:
<strong>15 دقيقة + 30 دقيقة</strong> بهذا الترتيب.
</p>

<p>مثال:</p>
<ul>
<li>قاد السائق 2 ساعات و30 دقيقة.</li>
<li>توقف 15 دقيقة.</li>
<li>قاد ساعتين إضافيتين.</li>
<li>يجب أن يأخذ 30 دقيقة على الأقل قبل مواصلة القيادة.</li>
</ul>

<h2>5️⃣ حدود القيادة اليومية والأسبوعية</h2>

<table>
<tr><th>الفترة</th><th>الحد</th></tr>
<tr><td>اليوم</td><td>9 ساعات عادةً</td></tr>
<tr><td>تمديد اليوم</td><td>حتى 10 ساعات، بحد أقصى مرتين في الأسبوع</td></tr>
<tr><td>أسبوع واحد</td><td>56 ساعة قيادة كحد أقصى</td></tr>
<tr><td>أسبوعان متتاليان</td><td>90 ساعة قيادة كحد أقصى</td></tr>
</table>

<p>
هذه الأرقام تتعلق بوقت القيادة وليست مجموع كل ساعات العمل.
</p>

<h2>6️⃣ الراحة اليومية</h2>

<p>
الراحة اليومية المنتظمة تكون عادةً <strong>11 ساعة على الأقل</strong>.
وتوجد حالات قانونية للراحة اليومية المخفضة إلى <strong>9 ساعات على الأقل</strong> وفق الشروط المحددة في القواعد الأوروبية.
</p>

<div class="warn">
لا تعتبر مجرد التوقف عن القيادة راحة تلقائياً. يجب أن تكون الفترة مسجلة بالطريقة الصحيحة وأن تستوفي شروط الراحة.
</div>

<h2>7️⃣ الراحة الأسبوعية</h2>

<p>
الراحة الأسبوعية المنتظمة هي <strong>45 ساعة على الأقل</strong>.
وتوجد إمكانية للراحة الأسبوعية المخفضة وفق شروط محددة، منها التعويض عندما يكون مطلوباً.
</p>

<p>
يجب على السائق أيضاً احترام توقيت بداية الراحة الأسبوعية وفق القواعد الأوروبية، وليس اختيار أي وقت بشكل عشوائي.
</p>

<h2>8️⃣ من المغرب إلى أوروبا: ماذا ينتبه إليه السائق؟</h2>

<div class="box">
إذا دخلت أوروبا بشاحنة تعمل في النقل الدولي، لا تعتمد على ما كنت تفعله في المغرب فقط.
من لحظة خضوع الرحلة للقواعد الأوروبية، يجب أن تكون سجلات القيادة والعمل والراحة قابلة للإثبات عند التفتيش.
</div>

<ul>
<li>احتفظ بسجلاتك بشكل مرتب.</li>
<li>لا تحاول تعديل التسجيل لإخفاء نشاط حقيقي.</li>
<li>عند تغيير النشاط، سجل النشاط الصحيح.</li>
<li>إذا طلبت منك السلطات السجلات، قدم السجلات المطلوبة للفترة القانونية.</li>
</ul>

<h2>9️⃣ التفتيش على الطريق</h2>

<p>
يمكن لسلطات الرقابة طلب سجلات النشاط الحالية والسجلات السابقة المطلوبة.
وفق القواعد الحالية، يجب أن يستطيع السائق إثبات نشاطه لليوم الحالي و<strong>الـ56 يوماً السابقة</strong>.
</p>

<div class="good">
<strong>نصيحة:</strong> لا تنتظر يوم التفتيش حتى تبحث عن سجلاتك. اجعلها مرتبة من أول يوم في الرحلة.
</div>

<h2>🔟 الانتقال من التاكوغراف الورقي إلى الرقمي</h2>

<p>
السائق الذي تعود على القرص الورقي سيجد أن التاكوغراف الرقمي يعمل بطريقة مختلفة، لكنه يعتمد على نفس الفكرة الأساسية:
<strong>تسجيل نشاط السائق الحقيقي.</strong>
</p>

<ul>
<li>بطاقة السائق شخصية ولا تُعطى لسائق آخر.</li>
<li>أدخل البطاقة قبل القيادة حسب تعليمات الجهاز.</li>
<li>اختر النشاط الصحيح عند تغيير العمل.</li>
<li>عند وجود فجوة في التسجيل، استخدم الإدخال اليدوي عندما يكون ذلك مطلوباً.</li>
<li>لا تقود وأنت تستخدم بطاقة سائق شخص آخر.</li>
</ul>

<h2>1️⃣1️⃣ التاكوغراف الذكي Smart Tachograph</h2>

<p>
التاكوغراف الذكي الحديث يستطيع تسجيل معلومات إضافية، ومنها موقع المركبة في لحظات محددة، ويستعمل بطاقة السائق لتخزين نشاطه.
</p>

<div class="warn">
<strong>مهم:</strong> توجد قواعد أوروبية للانتقال إلى التاكوغراف الذكي الإصدار الثاني (Smart Tachograph Version 2) للمركبات العاملة في النقل الدولي. لذلك يجب على السائق التأكد من تجهيز الشاحنة وبطاقة السائق وفق متطلبات الشركة والقواعد السارية.
</div>

<h2>1️⃣2️⃣ ماذا أفعل إذا كان التاكوغراف عاطلاً؟</h2>

<p>
إذا حدث عطل في جهاز التاكوغراف، لا تتجاهل المشكلة ولا تواصل العمل وكأن الجهاز سليم.
</p>

<ul>
<li>اتبع إجراء التسجيل اليدوي المطلوب.</li>
<li>احتفظ بالإثباتات المطلوبة.</li>
<li>أبلغ الشركة أو المسؤول عن الشاحنة.</li>
<li>يجب إصلاح الجهاز وفق الإجراءات المعتمدة.</li>
</ul>

<div class="warn">
لا تحاول إصلاح جهاز التاكوغراف بنفسك بطريقة غير معتمدة.
</div>

<h2>1️⃣3️⃣ أخطاء يقع فيها السائق الجديد</h2>

<ul>
<li>❌ القيادة أكثر من المسموح ثم محاولة تبريرها لاحقاً.</li>
<li>❌ تسجيل الراحة بينما السائق يقوم بعمل آخر.</li>
<li>❌ نسيان التسجيل اليدوي عند وجود فجوة.</li>
<li>❌ استعمال بطاقة سائق آخر.</li>
<li>❌ عدم الاحتفاظ بالسجلات المطلوبة.</li>
<li>❌ الاعتقاد أن وقت الانتظار دائماً راحة.</li>
<li>❌ تجاهل عطل التاكوغراف.</li>
<li>❌ الاعتماد على خبرة المغرب فقط عند دخول نظام أوروبي مختلف.</li>
</ul>

<h2>1️⃣4️⃣ مثال عملي لسائق مغربي</h2>

<div class="box">
<strong>06:00</strong> بداية العمل<br>
<strong>06:15 – 10:45</strong> قيادة = 4 ساعات و30 دقيقة<br>
<strong>10:45 – 11:30</strong> استراحة = 45 دقيقة<br>
<strong>11:30 – 14:00</strong> قيادة<br>
<strong>14:00 – 15:00</strong> تحميل/عمل آخر<br>
<strong>15:00 – 17:30</strong> قيادة<br>
<strong>بعد ذلك</strong> يخطط السائق لراحته وفق مجموع قيادته وباقي التزاماته.
</div>

<p>
هذا المثال للتوضيح فقط؛ لا يكفي وحده لتحديد قانونية رحلة كاملة، لأن الحساب يعتمد على كامل اليوم والأيام السابقة والراحة الأسبوعية وبقية ظروف الرحلة.
</p>

<h2>1️⃣5️⃣ عبور الحدود</h2>

<p>
عند عبور الحدود، لا تفترض أن تغيير الدولة يعني بدء حساب جديد.
وقت القيادة والراحة مرتبط بنشاط السائق والرحلة، وتوجد قواعد خاصة بتسجيل عبور الحدود بحسب نوع التاكوغراف والقواعد المطبقة.
</p>

<div class="good">
<strong>الأهم:</strong> لا تغيّر التسجيل بطريقة مصطنعة لمجرد أنك دخلت دولة جديدة. اتبع وظيفة الجهاز والتعليمات المعمول بها للشاحنة.
</div>

<h2>1️⃣6️⃣ ماذا يجب أن يتعلمه السائق المغربي قبل أول رحلة أوروبية؟</h2>

<ul>
<li>قراءة رموز التاكوغراف.</li>
<li>استعمال القرص الورقي إذا كانت الشاحنة مجهزة بتاكوغراف تناظري ومسموحاً به.</li>
<li>استعمال بطاقة السائق والتسجيل اليدوي في الرقمي.</li>
<li>حساب 4 ساعات و30 دقيقة.</li>
<li>حساب 9 و10 ساعات يومياً.</li>
<li>حساب 56 ساعة أسبوعياً و90 ساعة في أسبوعين.</li>
<li>فهم الراحة اليومية والأسبوعية.</li>
<li>معرفة ماذا يفعل عند العطل أو التفتيش.</li>
<li>الاحتفاظ بالسجلات المطلوبة.</li>
</ul>

