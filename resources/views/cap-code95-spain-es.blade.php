</div>

<div class="card">
<h2>🇵🇱🇱🇹 3. ¿Puede un conductor marroquí obtener el Code 95 en Polonia o Lituania y trabajar después en España?</h2>

<p>Esta cuestión no debe resumirse diciendo: «Voy como turista a Polonia o Lituania, obtengo el Code 95 y después puedo trabajar libremente en España».</p>

<p>La situación real depende de varios elementos: la base legal de la cualificación, el permiso de conducir utilizado, la residencia del conductor, la validez de los documentos y, sobre todo, el derecho legal a trabajar y residir en España.</p>

<p>Por eso, obtener una cualificación profesional en otro Estado miembro de la Unión Europea no significa automáticamente que el conductor tenga un permiso de trabajo español.</p>
</div>

<div class="card">
<h2>🇱🇹 4. Lituania: ¿qué hay que comprobar?</h2>

<p>La autoridad lituana <strong>Regitra</strong> ofrece información oficial sobre las tarjetas de cualificación del conductor (DQC) y los requisitos relacionados con la cualificación profesional.</p>

<p>La DQC puede estar relacionada con la cualificación profesional reconocida dentro del marco europeo, pero esto no debe confundirse con un permiso de residencia o de trabajo en España.</p>

<p>Antes de pagar por un curso o un trámite, el conductor debe comprobar directamente:</p>

<ul>
<li>qué permiso de conducir se utiliza;</li>
<li>sobre qué base legal se obtiene la cualificación;</li>
<li>qué documento se entrega;</li>
<li>durante cuánto tiempo es válido;</li>
<li>si la situación concreta permite trabajar legalmente en España.</li>
</ul>
</div>

<div class="card">
<h2>🇵🇱 5. Polonia: ¿qué hay que comprobar?</h2>

<p>En Polonia también es necesario comprobar la base legal de la cualificación profesional, el permiso de conducir utilizado, la situación de residencia del conductor y la validez de los documentos obtenidos.</p>

<p>No es correcto presentar como regla general que «tener un Code 95 polaco garantiza poder trabajar en España». El derecho a trabajar en España depende también de las normas españolas de inmigración y empleo aplicables al ciudadano de un país no perteneciente a la Unión Europea.</p>

<p>Por ello, antes de realizar cualquier pago, hay que verificar el procedimiento con las autoridades competentes y conservar los documentos oficiales que acrediten la cualificación obtenida.</p>
</div>

<div class="card">
<h2>🇪🇸 6. Contrato de trabajo y autorización para trabajar en España</h2>

<p>Para un conductor marroquí que no tenga ya derecho a trabajar en España, conseguir una cualificación profesional no sustituye el procedimiento necesario para obtener la autorización de residencia y trabajo cuando esta sea exigida.</p>

<p>Un contrato o una oferta de empleo de una empresa española y la correspondiente autorización administrativa forman parte de un proceso diferente del Code 95.</p>

<p>Por eso hay que distinguir claramente:</p>

<ul>
<li><strong>Cualificación profesional:</strong> demuestra que se cumplen determinados requisitos profesionales.</li>
<li><strong>Contrato de trabajo:</strong> establece la relación laboral con una empresa.</li>
<li><strong>Autorización de residencia y trabajo:</strong> determina si el ciudadano extranjero puede residir y trabajar legalmente en España.</li>
</ul>
</div>

<div class="card">
<h2>⏳ 7. La cuestión de los 6 meses para el permiso extranjero en España</h2>

<p>La Dirección General de Tráfico (DGT) establece reglas específicas para conducir en España con determinados permisos de conducir extranjeros.</p>

<p>En el caso de permisos procedentes de países con convenio de canje, cuando se cumplen las condiciones establecidas, la validez para conducir puede estar limitada a un período máximo de seis meses desde que el titular adquiere su residencia normal en España.</p>

<p>Por eso, un conductor que se instala legalmente en España debe comprobar su situación concreta y no asumir que un permiso extranjero seguirá siendo válido indefinidamente.</p>
</div>

<div class="card">
<h2>🇲🇦🇪🇸 8. Canje del permiso de conducir marroquí en España</h2>

<p>Marruecos figura entre los países que tienen un convenio de canje de permisos de conducir con España.</p>

<p>Sin embargo, el procedimiento depende de la categoría del permiso, de las condiciones del convenio y de la situación concreta del conductor. Para determinadas categorías profesionales, como C y D, pueden existir pruebas o requisitos adicionales.</p>

<p>Por ello, el conductor debe consultar siempre la información actualizada de la DGT antes de iniciar el procedimiento.</p>
</div>

<div class="card">
<h2>🚛 9. Tres ejemplos prácticos</h2>

<h3>Ejemplo 1 — C+E sin Code 95</h3>
<p>Un conductor puede tener un permiso C+E válido, pero eso no significa por sí solo que cumpla todos los requisitos de cualificación profesional necesarios para trabajar como conductor profesional.</p>

<h3>Ejemplo 2 — C+E + Code 95 europeo</h3>
<p>El conductor puede disponer de una cualificación profesional reconocida en el marco europeo. Aun así, debe comprobar si cumple los requisitos necesarios para trabajar legalmente en España.</p>

<h3>Ejemplo 3 — C+E + Code 95 + empresa española</h3>
<p>En este caso existen más elementos del proceso, pero todavía hay que comprobar la situación del permiso de conducir, la cualificación profesional y, cuando corresponda, la autorización de residencia y trabajo.</p>
</div>

<div class="card">
<h2>❌ 10. Lo que el Code 95 NO significa</h2>

<ul>
<li>No es un visado.</li>
<li>No es un permiso de residencia en España.</li>
<li>No es un permiso de trabajo español.</li>
<li>No convierte automáticamente un permiso de conducir marroquí en un permiso español.</li>
<li>No garantiza automáticamente un puesto de trabajo.</li>
</ul>

<p>El Code 95 es una cualificación profesional. Los demás requisitos deben analizarse por separado según la situación del conductor.</p>
</div>

<div class="card">
<h2>🔎 11. ¿Cómo verificar todo antes de pagar?</h2>

<p>Antes de pagar por un curso, una tarjeta profesional o cualquier trámite, el conductor debe pedir información clara y por escrito.</p>

<ul>
<li>¿Qué documento voy a obtener exactamente?</li>
<li>¿Qué autoridad oficial lo expide?</li>
<li>¿Con qué permiso de conducir se obtiene?</li>
<li>¿Cuál es la base legal del procedimiento?</li>
<li>¿Dónde será válido el documento?</li>
<li>¿El procedimiento me da derecho a trabajar en España?</li>
<li>¿Quién se encarga, en su caso, del contrato y de la autorización de residencia y trabajo?</li>
</ul>

<p>Si alguien afirma que un Code 95 obtenido en otro país garantiza automáticamente un trabajo en España, es importante pedir la base legal y comprobar la información directamente con las autoridades correspondientes.</p>
</div>

<div class="card">
<h2>⚠️ 12. Atención a las promesas de trabajo</h2>

<p>Los conductores deben tener cuidado con cualquier intermediario que prometa un trabajo en España únicamente a cambio de dinero por un supuesto Code 95.</p>

<p>Una cualificación profesional y un permiso de trabajo son cuestiones diferentes. Antes de entregar dinero o documentos personales, conviene verificar la empresa, el contrato, la autoridad que expide el documento y el procedimiento legal aplicable.</p>
</div>

<div class="card">
<h2>✅ Conclusión</h2>

<p>Para un conductor marroquí, el Code 95 es un elemento importante de la cualificación profesional, pero no debe confundirse con el derecho a residir o trabajar en España.</p>

<p>Obtener una cualificación en Polonia o Lituania puede implicar requisitos específicos y debe analizarse según la situación concreta del conductor. El permiso de conducir, la cualificación profesional, el contrato de trabajo y la autorización de residencia y trabajo son elementos diferentes.</p>

<p><strong>Antes de pagar o entregar documentos personales, comprueba siempre la información con las autoridades oficiales.</strong></p>
</div>

