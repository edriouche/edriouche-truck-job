<h2>📌 ¿Por qué es importante este tema?</h2>
<p>Muchos conductores marroquíes escuchan que pueden obtener el CAP / Code 95 en Polonia o Lituania y después trabajar directamente en España. Esta cuestión necesita una explicación clara porque se mezclan varios conceptos diferentes: permiso de conducir, cualificación profesional, contrato de trabajo y permiso de residencia y trabajo.</p>
</div>

<div class="card">
<h2>🚛 1. ¿Qué es el CAP / Code 95?</h2>
<p>El CAP / Code 95 está relacionado con la cualificación profesional de los conductores de vehículos de transporte por carretera. En la Unión Europea, esta cualificación está regulada por normas europeas y nacionales.</p>

<p>Para trabajar como conductor profesional de camión, no basta con tener una categoría C o CE en el permiso de conducir. También hay que comprobar los requisitos de cualificación profesional aplicables al conductor y al trabajo que va a realizar.</p>
</div>

<div class="card">
