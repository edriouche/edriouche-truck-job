<p>دليل عملي للسائق المهني في النقل البري لتجنب المخالفات</p>
</header>

<div class="container">

<div class="warning">
<strong>⚠️ تنبيه قانوني مهم:</strong>
هذا الدليل تعليمي وتوعوي للسائقين المهنيين، ولا يغني عن الرجوع إلى النصوص الرسمية السارية أو استشارة مختص عند وجود حالة خاصة.
القواعد الأوروبية والوطنية قد تتغير، كما توجد استثناءات خاصة ببعض أنواع النقل والمركبات والعمليات.
</div>

<div class="card">
<h2>🇪🇺 1. أوقات القيادة والتوقف والراحة</h2>

<div class="article">
<strong>القيادة اليومية — المادة 6:</strong>
الحد الأقصى المعتاد للقيادة هو <strong>9 ساعات في اليوم</strong>، ويمكن تمديده إلى <strong>10 ساعات مرتين في الأسبوع</strong>.
</div>

<div class="article">
<strong>القيادة الأسبوعية:</strong>
لا يجوز أن تتجاوز القيادة <strong>56 ساعة في الأسبوع</strong>.
</div>

<div class="article">
<strong>خلال أسبوعين متتاليين:</strong>
لا يجوز أن تتجاوز مدة القيادة الإجمالية <strong>90 ساعة</strong>.
</div>

<div class="article">
<strong>التوقف بعد القيادة — المادة 7:</strong>
بعد مجموع قيادة يبلغ <strong>4 ساعات و30 دقيقة</strong> يجب أخذ توقف لا يقل عن <strong>45 دقيقة</strong>، ما لم يبدأ السائق فترة راحة.
ويمكن تقسيم التوقف وفق الشروط القانونية إلى <strong>15 دقيقة ثم 30 دقيقة</strong>.
</div>

<div class="article">
<strong>الراحة اليومية — المادة 8:</strong>
يجب أخذ فترة راحة يومية منتظمة لا تقل عن <strong>11 ساعة</strong>.
ويمكن في الحالات التي يسمح بها القانون أخذ راحة يومية مخفضة لا تقل عن <strong>9 ساعات</strong>، مع احترام القيود والتعويضات المقررة.
</div>

<div class="article">
<strong>الراحة اليومية المجزأة:</strong>
يمكن، وفق الشروط القانونية، تقسيم الراحة اليومية المنتظمة إلى فترة أولى لا تقل عن <strong>3 ساعات</strong> وفترة ثانية لا تقل عن <strong>9 ساعات</strong>.
</div>

<div class="article">
<strong>الراحة الأسبوعية:</strong>
يجب احترام قواعد الراحة الأسبوعية المنتظمة والمخفضة والتعويض عنها وفق المادة 8 من اللائحة الأوروبية.
الراحة الأسبوعية المنتظمة تكون عادة <strong>45 ساعة على الأقل</strong>، ويمكن تخفيضها في الحالات المسموح بها مع التعويض وفق القانون.
</div>

<div class="info">
<strong>📌 قاعدة مهمة:</strong>
يجب على السائق تنظيم عمله بحيث يستطيع احترام أوقات القيادة والتوقف والراحة، ولا يجوز للشركة أن تضغط عليه لتنفيذ برنامج يخالف القواعد.
</div>

</div>

<div class="card">
<h2>🧭 2. التاكغراف</h2>

<div class="article">
<strong>Reglamento (UE) 165/2014:</strong>
ينظم التاكغراف واستعماله وتسجيل أنشطة السائق والبيانات المتعلقة بالقيادة والراحة وغيرها من الأنشطة.
</div>

<div class="article">
<strong>🚨 منع التلاعب:</strong>
يحظر التلاعب بالتاكغراف أو بياناته أو استعمال وسائل تهدف إلى تغيير أو إخفاء النشاط الحقيقي للسائق.
</div>

<div class="article">
<strong>📋 أثناء التفتيش:</strong>
يجب أن تكون البيانات والتسجيلات والوثائق المطلوبة متاحة وفق القواعد المطبقة على الرحلة والمركبة والفترة التي يتم فحصها.
</div>

<div class="article">
<strong>🌍 ابتداءً من 1 يوليو 2026:</strong>
في النقل الدولي أو عمليات الكابوتاج، أصبح التاكغراف إلزاميًا أيضًا للمركبات المخصصة لنقل البضائع التي تتجاوز كتلتها القصوى المسموح بها <strong>2.5 طن</strong> وفق الشروط المحددة في القواعد الأوروبية.
</div>

<div class="article">
<strong>🛰️ التاكغراف الذكي:</strong>
توجد قواعد أوروبية متدرجة لتجهيز المركبات بالتاكغراف الذكي، وخاصة في النقل الدولي، لذلك يجب التحقق من نوع المركبة وتاريخ تسجيلها ونوع العملية.
</div>

</div>

<div class="card">
<h2>🚨 3. المخالفات في إسبانيا</h2>

<div class="article">
<strong>LOTT — Ley 16/1987:</strong>
تنظم إسبانيا النقل البري ونظام الرقابة والعقوبات، وتتضمن المواد <strong>140 و141</strong> تصنيفات للمخالفات، ومنها مخالفات مرتبطة بأوقات القيادة والراحة والتاكغراف.
</div>

<div class="article">
<strong>⚠️ درجة المخالفة مهمة:</strong>
لا يكفي القول إن المخالفة "مخالفة تاكغراف" أو "مخالفة راحة"، لأن التصنيف والعقوبة يعتمدان على نوع المخالفة والوقائع والنص القانوني الساري.
</div>

<div class="article">
<strong>❗ لا تعتمد على مبلغ غرامة قديم:</strong>
لا نضع في هذه الصفحة مبالغ ثابتة للغرامات لأن القواعد والتصنيفات قد تتغير، وقد تختلف النتيجة حسب نوع المخالفة والظروف القانونية.
</div>

</div>

<div class="card">
<h2>🎓 4. CAP — تأهيل السائق المهني في إسبانيا</h2>

<p>
شهادة <strong>CAP — Certificado de Aptitud Profesional</strong>
مرتبطة بالتأهيل الأولي والتكوين المستمر للسائقين المهنيين في النقل البري وفق القواعد الإسبانية والأوروبية المطبقة.
</p>

<div class="article">
<strong>Real Decreto 284/2021:</strong>
ينظم في إسبانيا التأهيل الأولي والتكوين المستمر للسائقين المعنيين بالنقل البري.
</div>

<div class="article">
<strong>📅 تحديث مهم في 2026:</strong>
صدر <strong>Real Decreto 487/2026</strong> لتعديل Real Decreto 284/2021.
بعض التعديلات المنشورة في يونيو 2026 تدخل حيز التنفيذ في <strong>18 سبتمبر 2026</strong>، لذلك يجب التمييز بين القواعد السارية حاليًا والتعديلات التي لم تدخل حيز التنفيذ بعد.
</div>

<div class="info">
<strong>📌 للسائق القادم للعمل في إسبانيا:</strong>
متطلبات CAP تعتمد على وضع السائق ونوع النقل ورخصته وتأهيله والقواعد المطبقة عليه. لا تفترض أن امتلاك رخصة قيادة أجنبية يعني تلقائيًا استيفاء متطلبات CAP.
</div>

</div>

<div class="card">
<h2>🚛 5. قبل الانطلاق</h2>

<ul>
<li>✅ تحقق من رخصة القيادة والوثائق المطلوبة.</li>
<li>✅ تحقق من متطلبات CAP إذا كانت مطبقة عليك.</li>
<li>✅ تحقق من التاكغراف وطريقة تسجيل نشاطك.</li>
<li>✅ راجع أوقات القيادة والتوقف والراحة.</li>
<li>✅ تأكد من حالة المركبة وسلامتها.</li>
<li>✅ تأكد من تثبيت الحمولة بطريقة صحيحة.</li>
<li>✅ تأكد من وثائق البضاعة والنقل.</li>
<li>✅ في نقل البضائع الخطرة، تحقق من متطلبات ADR.</li>
<li>✅ احتفظ بالوثائق والتسجيلات المطلوبة أثناء الرحلة.</li>
</ul>

