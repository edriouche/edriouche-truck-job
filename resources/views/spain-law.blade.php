<div class="card">
<h2>🎓 4. CAP — تأهيل السائق المهني في إسبانيا</h2>

<p>
شهادة <strong>CAP — Certificado de Aptitud Profesional</strong>
مرتبطة بالتأهيل الأولي والتكوين المستمر للسائقين المهنيين في النقل البري وفق القواعد الإسبانية والأوروبية المطبقة.
</p>

<div class="article">
<strong>Real Decreto 284/2021:</strong>
ينظم في إسبانيا التأهيل الأولي والتكوين المستمر للسائقين المعنيين بالنقل البري.
</div>

<div class="article">
<strong>📅 تحديث مهم في 2026:</strong>
صدر <strong>Real Decreto 487/2026</strong> لتعديل Real Decreto 284/2021.
بعض التعديلات المنشورة في يونيو 2026 تدخل حيز التنفيذ في <strong>18 سبتمبر 2026</strong>، لذلك يجب التمييز بين القواعد السارية حاليًا والتعديلات التي لم تدخل حيز التنفيذ بعد.
</div>

<div class="info">
<strong>📌 للسائق القادم للعمل في إسبانيا:</strong>
متطلبات CAP تعتمد على وضع السائق ونوع النقل ورخصته وتأهيله والقواعد المطبقة عليه. لا تفترض أن امتلاك رخصة قيادة أجنبية يعني تلقائيًا استيفاء متطلبات CAP.
</div>

</div>

