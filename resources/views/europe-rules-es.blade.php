<h1>Reglas europeas para conductores profesionales</h1>
<p>Guía práctica para conductores de camión que trabajan o desean trabajar en Europa.</p>

<div class="card"><h2>1. Tiempo máximo de conducción diaria</h2>
<p>La conducción diaria máxima es de 9 horas. Puede ampliarse a 10 horas como máximo dos veces por semana.</p></div>

<div class="card"><h2>2. Tiempo de conducción semanal</h2>
<p>El máximo semanal es de 56 horas. En dos semanas consecutivas no se pueden superar 90 horas.</p></div>

<div class="card"><h2>3. Pausa de conducción</h2>
<p>Después de un máximo de 4 horas y 30 minutos de conducción, se debe realizar una pausa de 45 minutos. Puede dividirse en 15 minutos + 30 minutos.</p></div>

<div class="card"><h2>4. Descanso diario</h2>
<p>El descanso diario normal es de 11 horas. Puede dividirse en 3 + 9 horas. El descanso reducido de 9 horas está limitado entre los descansos semanales.</p></div>

<div class="card"><h2>5. Descanso semanal</h2>
<p>El descanso semanal normal es de 45 horas. En determinadas condiciones puede reducirse a 24 horas, con la compensación correspondiente.</p></div>

<div class="card"><h2>6. Descanso dentro de la cabina</h2>
<p>El descanso semanal normal de 45 horas o más no debe realizarse en la cabina del vehículo. Algunos descansos diarios y descansos semanales reducidos pueden realizarse en el vehículo cuando se cumplen las condiciones legales.</p></div>

<div class="card"><h2>7. Tiempo de conducción y tiempo de trabajo</h2>
<p>El tiempo de trabajo puede incluir carga y descarga, mantenimiento, trabajos técnicos, supervisión y determinadas tareas administrativas. No debe confundirse con el tiempo de conducción.</p></div>

<div class="card"><h2>8. Tiempo de trabajo semanal</h2>
<p>La jornada media de trabajo es de 48 horas semanales. Puede llegar a 60 horas en una semana si la media durante el período de referencia aplicable no supera 48 horas.</p></div>

<div class="card"><h2>9. Pausas durante el trabajo</h2>
<p>Las pausas de tiempo de trabajo son diferentes de la pausa de conducción de 45 minutos. Las reglas concretas dependen también de la normativa nacional y de los convenios aplicables.</p></div>

<div class="card"><h2>10. Trabajo nocturno</h2>
<p>Cuando existe trabajo nocturno, pueden aplicarse límites específicos al tiempo de trabajo dentro de un período de 24 horas, de acuerdo con la legislación europea y nacional aplicable.</p></div>

<div class="card"><h2>11. Conducción en equipo</h2>
<p>La conducción con varios conductores tiene reglas especiales sobre los períodos de descanso y la organización del trabajo.</p></div>

<div class="card"><h2>12. Ferry y tren</h2>
<p>Existen reglas especiales para determinados descansos durante los viajes en ferry o tren, siempre que se cumplan las condiciones establecidas por la normativa.</p></div>

<div class="card"><h2>13. Tacógrafo</h2>
<p>El tacógrafo registra la conducción, las pausas, los descansos, el trabajo y la disponibilidad. El conductor debe utilizar su propia tarjeta de conductor y nunca prestarla a otra persona.</p></div>

<div class="card"><h2>14. Errores graves que deben evitarse</h2>
<p>No conducir más allá de los límites permitidos, no manipular el tacógrafo, respetar los descansos y conservar correctamente los documentos profesionales.</p></div>

<div class="card"><h2>15. Consejo para el conductor marroquí</h2>
<p>Para trabajar legalmente en Europa hay que distinguir entre el permiso de conducir, la cualificación profesional, la tarjeta de tacógrafo y el derecho legal a trabajar y residir.</p></div>

<div class="card"><p><strong>Importante:</strong> esta página es una guía informativa. El conductor debe comprobar siempre la normativa europea y nacional vigente para su situación.</p></div>

