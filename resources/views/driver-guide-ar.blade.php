<h2 style="text-align:center;">🇲🇦 دليل السائق المغربي: من المبتدئ إلى الاحتراف</h2>
<p style="text-align:center;line-height:2.0;font-size:20px;">هذا الدليل يساعد السائق على تجهيز نفسه للبحث عن العمل والتقدم إلى الشركات بطريقة مهنية ومنظمة.</p>

<div style="margin-top:25px;">
<h3>🟢 1. كيف تبدأ كسائق شاحنة؟</h3>
<p style="line-height:2;font-size:20px;">ابدأ بالتأكد من فئة رخصة السياقة المناسبة، ثم اكتسب التكوين والخبرة تدريجيًا. لا تبحث عن أول وظيفة فقط؛ ابحث عن المكان الذي يساعدك على بناء خبرة مهنية حقيقية.</p>

<h3>📄 2. جهّز ملفك المهني</h3>
<p style="line-height:2;font-size:20px;">جهّز ملفًا مرتبًا يحتوي على السيرة الذاتية، صورة مهنية، رخصة السياقة، بطاقة السائق المهنية، شهادات التكوين والخبرة، وأي شهادات إضافية مطلوبة لنوع النقل الذي تريد العمل فيه.</p>

<h3>📝 3. كيف تكتب CV احترافيًا؟</h3>
<p style="line-height:2;font-size:20px;">اكتب الاسم ووسائل الاتصال والمدينة، فئات الرخص، سنوات الخبرة، أنواع الشاحنات التي قدتها، أنواع النقل التي مارستها، الشهادات والتكوينات، واللغات. اجعل المعلومات واضحة وصادقة ومختصرة.</p>

<h3>📸 4. الصورة المهنية</h3>
<p style="line-height:2;font-size:20px;">استعمل صورة حديثة وواضحة وملائمة للعمل، بخلفية بسيطة وملابس محترمة. تجنب الصور العائلية أو الصور غير الواضحة داخل CV.</p>

<h3>📑 5. رتّب وثائقك</h3>
<p style="line-height:2;font-size:20px;">احتفظ بنسخ واضحة ومنظمة من وثائقك. وعند طلب الشركة ملف PDF، اجمع الوثائق المطلوبة فقط وبترتيب واضح.</p>

<h3>🔎 6. كيف تبحث عن شركة مناسبة؟</h3>
<p style="line-height:2;font-size:20px;">ابدأ بموقع الشركة الرسمي وصفحة التوظيف الرسمية. تحقق من اسم الشركة ونشاطها ومعلومات الاتصال قبل إرسال طلبك. لا تعتمد على إعلان مجهول المصدر.</p>

<h3>📧 7. كيف ترسل طلب العمل؟</h3>
<p style="line-height:2;font-size:20px;">اكتب رسالة قصيرة ومحترمة، اذكر فيها الوظيفة التي ترغب فيها، وأرفق CV والوثائق المطلوبة. استعمل البريد الإلكتروني أو منصة التوظيف الرسمية للشركة متى كانت متاحة.</p>

<h3>🤝 8. كيف تستعد لمقابلة العمل؟</h3>
<p style="line-height:2;font-size:20px;">راجع معلومات الشركة، واعرف نوع الشاحنة والعمل والمسار المتوقع. حضّر وثائقك، وأجب بصدق عن خبرتك وقدرتك على تحمل مسؤولية الشاحنة والحمولة.</p>

<h3>🚚 9. نصائح للسائق في أول عمل</h3>
<p style="line-height:2;font-size:20px;">افحص الشاحنة قبل الانطلاق، اهتم بالسلامة وتثبيت الحمولة، احترم تعليمات الشركة وقواعد الطريق، وسجّل الأعطال والملاحظات وأبلغ المسؤول عنها.</p>

<h3>⚠️ 10. أخطاء يجب تجنبها</h3>
<p style="line-height:2;font-size:20px;">لا تضع خبرة غير حقيقية في CV، ولا ترسل وثائقك إلى أشخاص مجهولين، ولا تقبل شروطًا لا تفهمها. لا تدفع المال لشخص مقابل وعد بالتوظيف.</p>

<h3>🛡️ 11. احمِ نفسك من السماسرة</h3>
<p style="line-height:2;font-size:20px;">تعامل مباشرة مع الشركة كلما أمكن. تحقق من البريد الإلكتروني والموقع الرسمي واسم الشركة قبل أي خطوة، ولا تعتبر العقد أو العرض حقيقيًا إلا بعد التحقق من مصدره.</p>

