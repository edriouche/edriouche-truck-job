<section class="card">
<h2>1. Driving and rest periods</h2>
<p>Professional drivers must follow the driving-time, break and rest-period rules that apply to their journey and operation. The applicable requirements can depend on the type of transport, vehicle, exemptions and current legislation.</p>
<p>Check the current official rules before relying on a summary or planning a trip.</p>
</section>
<section class="card">
<h2>2. Tachograph responsibilities</h2>
<ul>
<li>Use the required tachograph and driver card when applicable.</li>
<li>Make sure records and entries are accurate.</li>
<li>Follow the rules for manual entries, printouts and records when relevant.</li>
<li>Report equipment faults and follow the legally required procedure.</li>
</ul>
<p>Whether a particular tachograph card or system is required depends on the vehicle, operation and applicable rules.</p>
</section>
<section class="card">
<h2>3. Documents and qualifications</h2>
<p>Before starting work, confirm which documents are required for the vehicle and the job. These may include the appropriate driving licence, professional qualification, identity and transport documents, and any required authorisation to reside and work in the destination country.</p>
<p>A professional qualification or employment contract does not automatically provide immigration permission or make every foreign driving licence valid for every purpose.</p>
</section>
<section class="card">
<h2>4. Vehicle and load safety</h2>
<ul>
<li>Carry out the required vehicle checks before departure.</li>
<li>Secure the load and respect applicable weight and dimension limits.</li>
<li>Check tyres, lights, brakes and visible defects.</li>
<li>Follow road signs, speed limits, parking restrictions and workplace safety procedures.</li>
<li>Never drive when fatigue makes driving unsafe.</li>
</ul>
</section>
<section class="card warning">
<h2>5. Rules vary by country and operation</h2>
<p>Do not assume that one summary covers every European country, vehicle type or transport activity. International transport, domestic transport, dangerous goods and other specialised operations can have additional requirements.</p>
<p>Confirm important legal questions with the competent official authority or a qualified professional before taking action.</p>
</section>
<section class="card">
<h2>6. Protect yourself when seeking work</h2>
<ul>
<li>Verify the employer using reliable company information.</li>
<li>Request the written contract and understand the pay, duties and working conditions.</li>
<li>Check work and residence authorisation requirements for your individual situation.</li>
<li>Be cautious of anyone promising a guaranteed job or visa in return for payment.</li>
</ul>
