<h1>⏱️ دليل التاكوغراف للسائق في أوروبا</h1>

<p style="text-align:center;line-height:2;font-size:17px;">
شرح عملي للسائق المهني: ماذا تسجل في التاكوغراف أثناء القيادة،
التحميل، التفريغ، الانتظار، الاستراحة والراحة.
</p>

<div class="warning">
<strong>⚠️ القاعدة الأساسية:</strong><br>
التاكوغراف ليس جهازًا لاختيار ما يريده السائق؛ يجب أن يعكس النشاط الحقيقي
الذي يقوم به السائق. اختيار النشاط الخطأ قد يؤدي إلى تسجيل غير صحيح.
</div>

<div class="card">
<h2>🚛 1. أثناء القيادة</h2>
<p>
عندما تكون الشاحنة في حالة قيادة، يسجل التاكوغراف نشاط القيادة تلقائيًا
في الأجهزة التي تعمل بصورة صحيحة.
</p>

<div class="example">
📌 مثال:<br>
تشغل الشاحنة وتنطلق من موقفها → تبدأ القيادة → التاكوغراف يسجل القيادة.
</div>
</div>

<div class="card">
<h2>🔨 2. التحميل والتفريغ</h2>
<p>
إذا كنت تقوم بالتحميل أو التفريغ أو بعمل آخر مرتبط بالنقل،
فهذا ليس وقت راحة لمجرد أن الشاحنة متوقفة.
</p>

<div class="example">
📌 مثال:<br>
وصلت إلى العميل الساعة 10:00 وبدأت تفريغ البضاعة حتى 11:00.
هذه ساعة عمل وليست ساعة راحة.
</div>
</div>

<div class="card">
<h2>🔧 3. عمل آخر</h2>
<p>
يُستخدم نشاط العمل الآخر عندما تقوم بأعمال مرتبطة بالعمل
ولا تكون في حالة قيادة.
</p>

<p>
مثل بعض أعمال التحميل والتفريغ، فحص المركبة، تثبيت الحمولة،
أو أعمال أخرى تدخل ضمن واجبات السائق.
</p>
</div>

<div class="card">
<h2>⏳ 4. فترة التوفر</h2>
<p>
فترة التوفر ليست هي نفسها الراحة.
توجد حالات قانونية محددة لفترة التوفر، ولذلك لا ينبغي للسائق
اختيارها لمجرد أنه ينتظر.
</p>

<div class="example">
📌 مثال:<br>
إذا كنت تنتظر وأنت ملزم بالبقاء مستعدًا لاستئناف العمل،
فلا تفترض تلقائيًا أن هذا وقت راحة.
يجب معرفة طبيعة الانتظار وشروطه قبل اختيار النشاط.
</div>
</div>

<div class="card">
<h2>☕ 5. الاستراحة</h2>
<p>
الاستراحة تعني أن السائق لا يقوم بعمل أو مهمة أخرى،
وتستخدم خصوصًا لاستيفاء متطلبات استراحة القيادة.
</p>

<div class="example">
📌 مثال:<br>
قدت 4 ساعات و30 دقيقة → توقفت وتفرغت للاستراحة 45 دقيقة
→ بعد ذلك يمكنك مواصلة القيادة وفق الحدود القانونية.
</div>
</div>

<div class="card">
<h2>🛏️ 6. الراحة اليومية</h2>
<p>
عندما تنتهي فترة العمل وتدخل في الراحة اليومية،
يجب تسجيل النشاط المناسب لفترة الراحة.
</p>

<p>
الراحة اليومية العادية تكون 11 ساعة على الأقل،
مع وجود حالات قانونية للراحة المخفضة أو المجزأة.
</p>
</div>

<div class="card">
<h2>📆 7. الراحة الأسبوعية</h2>
<p>
الراحة الأسبوعية لها قواعد خاصة، ولا ينبغي الخلط بينها
وبين الاستراحة القصيرة أو الراحة اليومية.
</p>

<p>
الراحة الأسبوعية العادية هي 45 ساعة على الأقل،
مع وجود شروط خاصة للراحة الأسبوعية المخفضة والتعويض.
</p>
</div>

<div class="card">
<h2>🔄 8. عند تغيير الشاحنة</h2>
<p>
عند الانتقال من شاحنة إلى أخرى، يجب التأكد من تسجيل النشاط
والبيانات المطلوبة على التاكوغراف الجديد بطريقة صحيحة.
</p>

<p>
في التاكوغراف الرقمي، يجب إدخال بطاقة السائق الشخصية
واستخدامها وفق الإجراءات المطلوبة.
</p>
</div>

<div class="card">
<h2>🧾 9. عند وجود بيانات ناقصة</h2>
<p>
إذا كان هناك نشاط لم يسجل بشكل صحيح أو فترة تحتاج إلى إدخال يدوي،
يجب اتباع إجراءات التاكوغراف المعمول بها وإدخال البيانات الحقيقية.
</p>

<div class="example">
📌 لا تختر نشاطًا عشوائيًا فقط لإكمال الشاشة.
الهدف هو أن تعكس البيانات ما حدث فعليًا.
</div>
</div>

<div class="card">
<h2>🚨 10. عند عطل التاكوغراف</h2>
<p>
عند حدوث عطل، يجب اتباع الإجراءات القانونية الخاصة بالعطل،
والحفاظ على السجلات المطلوبة، وإصلاح الجهاز في أقرب وقت ممكن
وفق القواعد المطبقة.
</p>

<p>
لا تتجاهل العطل ولا تستمر وكأن الجهاز يعمل بشكل طبيعي.
</p>
</div>

<div class="danger">
<h2>❌ 11. أخطاء شائعة</h2>
<ul style="line-height:2.2;">
<li>❌ اعتبار التحميل والتفريغ راحة.</li>
<li>❌ اختيار الراحة أثناء القيام بعمل.</li>
<li>❌ اختيار فترة التوفر دون تحقق من شروطها.</li>
<li>❌ استعمال بطاقة سائق آخر.</li>
<li>❌ محاولة تغيير البيانات لإخفاء القيادة أو العمل.</li>
<li>❌ تجاهل عطل التاكوغراف.</li>
</ul>
</div>

<div class="warning">
<h2>🇲🇦 12. مثال عملي للسائق المغربي</h2>

<p>
بدأت العمل الساعة <strong>08:00</strong>.
</p>

<p>
🚛 08:00 → 10:30: قيادة.
<br>
🔨 10:30 → 11:15: تحميل/عمل.
<br>
🚛 11:15 → 13:15: قيادة.
<br>
☕ 13:15 → 14:00: استراحة.
</p>

<p>
هنا يجب الانتباه إلى أن <strong>وقت العمل ووقت القيادة ليسا الشيء نفسه</strong>.
والاستراحة لا تُحسب كعمل عندما تكون استراحة حقيقية.
</p>

<p>
هذا المثال للتوضيح فقط؛ الحساب القانوني النهائي يعتمد على كامل يوم السائق
والأسبوعين المتتاليين وباقي الظروف.
</p>
</div>

<div class="card">
<h2>🛡️ 13. قاعدة ذهبية</h2>
<p>
<strong>
سجّل ما تفعله فعليًا، واحترم حدود القيادة والعمل والراحة،
ولا تحاول جعل التاكوغراف يقول شيئًا مختلفًا عما حدث على الطريق.
</strong>
</p>
